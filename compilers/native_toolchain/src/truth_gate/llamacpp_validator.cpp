bool LlamaCPPValidator_CompareLogits(const float* rawrxd_logits,
                                        const float* reference_logits,
                                        int vocab_size,
                                        double* relative_error) {
    if (!rawrxd_logits || !reference_logits || !relative_error) return false;
    
    double sum_sq_error = 0.0;
    double sum_sq_ref = 0.0;
    
    for (int i = 0; i < vocab_size; i++) {
        double diff = rawrxd_logits[i] - reference_logits[i];
        sum_sq_error += diff * diff;
        sum_sq_ref += reference_logits[i] * reference_logits[i];
    }
    
    if (sum_sq_ref > 0) {
        *relative_error = sqrt(sum_sq_error / sum_sq_ref);
    } else {
        *relative_error = 0.0;
    }
    
    return true;
}

bool LlamaCPPValidator_CompareTokens(const int* rawrxd_tokens,
                                        const int* reference_tokens,
                                        int num_tokens) {
    if (!rawrxd_tokens || !reference_tokens || num_tokens <= 0) return false;
    
    for (int i = 0; i < num_tokens; i++) {
        if (rawrxd_tokens[i] != reference_tokens[i]) {
            return false;
        }
    }
    
    return true;
}

