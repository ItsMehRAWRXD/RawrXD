; ============================================
; GENERATE ASSEMBLY HEADER
; ============================================
generate_asm_header:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    ; Copy header to output buffer
    lea rsi, [asm_header]
    lea rdi, [output_buffer]
    mov rcx, asm_header_len
    rep movsb

    mov [output_size], rdi
    sub rdi, output_buffer

    leave
    ret

; ============================================
; GENERATE CODE
; ============================================
generate_code:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    ; Generate text section
    mov rdi, [output_size]
    lea rdi, [output_buffer + rdi]
    lea rsi, [asm_text_start]
    mov rcx, asm_text_start_len
    rep movsb

    ; Generate main function
    mov rdi, [output_size]
    add rdi, asm_text_start_len
    lea rdi, [output_buffer + rdi]
    lea rsi, [asm_func_start]
    mov rcx, asm_func_start_len
    rep movsb

    mov rax, rdi
    sub rax, output_buffer
    mov [output_size], rax

    leave
    ret

; ============================================
; GENERATE ASSEMBLY FOOTER
; ============================================
generate_asm_footer:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    mov rdi, [output_size]
    lea rdi, [output_buffer + rdi]
    lea rsi, [asm_func_end]
    mov rcx, asm_func_end_len
    rep movsb

    mov rax, rdi
    sub rax, output_buffer
    mov [output_size], rax

    leave
    ret

; ============================================
; WRITE OUTPUT FILE
; ============================================
write_output_file:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    ; Check if output filename specified
    mov al, [outfilename_buffer]
    test al, al
    jnz .has_output

    ; Default output: input.asm
    lea rdi, [outfilename_buffer]
    lea rsi, [filename_buffer]
.copy_name:
    lodsb
    stosb
    test al, al
    jnz .copy_name

    ; Replace extension with .asm
    mov rcx, rdi
    sub rcx, outfilename_buffer
    sub rcx, 2
.find_ext:
    cmp byte [rdi-1], '.'
    je .found_ext
    dec rdi
    loop .find_ext
    jmp .has_output

.found_ext:
    lea rdi, [outfilename_buffer]
    add rdi, rcx
    mov byte [rdi], 'a'
    mov byte [rdi+1], 's'
    mov byte [rdi+2], 'm'
    mov byte [rdi+3], 0

.has_output:
    ; Create output file
    lea rcx, [outfilename_buffer]
    mov rdx, 0x40000000          ; GENERIC_WRITE
    xor r8, r8                   ; No share
    xor r9, r9                   ; No security
    mov qword [rsp+32], 2        ; CREATE_ALWAYS
    mov qword [rsp+40], 0x80     ; FILE_ATTRIBUTE_NORMAL
    mov qword [rsp+48], 0
    call CreateFileA

    cmp rax, -1
    je .error

    mov [outfile_handle], rax

    ; Write output
    mov rcx, rax
    lea rdx, [output_buffer]
    mov r8, [output_size]
    lea r9, [written]
    mov qword [rsp+32], 0
    call WriteFile

    ; Close file
    mov rcx, [outfile_handle]
    call CloseHandle

    mov rax, 1
    jmp .done

.error:
    xor rax, rax

.done:
    leave
    ret

; ============================================
; PARSE ARGUMENTS
; ============================================
parse_arguments:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    call GetCommandLineA
    mov rsi, rax

    ; Skip program name
.skip_prog:
    lodsb
    test al, al
    jz .no_args
    cmp al, ' '
    jne .skip_prog

    ; Skip spaces
.skip_spaces:
    lodsb
    cmp al, ' '
    je .skip_spaces
    dec rsi

    mov al, [rsi]
    test al, al
    jz .no_args

    ; Copy filename
    lea rdi, [filename_buffer]
.copy_loop:
    lodsb
    cmp al, ' '
    je .copy_done
    test al, al
    jz .copy_done
    stosb
    jmp .copy_loop
.copy_done:
    mov byte [rdi], 0

    ; Check for -o option
    cmp al, ' '
    jne .done
    
.skip_to_o:
    lodsb
    cmp al, '-'
    je .check_o
    test al, al
    jz .done
    jmp .skip_to_o

.check_o:
    lodsb
    cmp al, 'o'
    jne .done
    
    ; Skip spaces
.skip_o_spaces:
    lodsb
    cmp al, ' '
    je .skip_o_spaces
    dec rsi

    ; Copy output filename
    lea rdi, [outfilename_buffer]
.copy_out:
    lodsb
    cmp al, ' '
    je .out_done
    test al, al
    jz .out_done
    stosb
    jmp .copy_out
.out_done:
    mov byte [rdi], 0

.done:
    lea rax, [filename_buffer]
    leave
    ret

.no_args:
    xor rax, rax
    leave
    ret

; ============================================
; OPEN INPUT FILE
; ============================================
open_input_file:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    mov [rsp+56], rcx

    mov rdx, 0x80000000          ; GENERIC_READ
    xor r8, r8                   ; No share
    xor r9, r9                   ; No security
    mov qword [rsp+32], 3        ; OPEN_EXISTING
    mov qword [rsp+40], 0x80     ; FILE_ATTRIBUTE_NORMAL
    mov qword [rsp+48], 0
    call CreateFileA

    cmp rax, -1
    je .error

    mov [infile_handle], rax

    ; Read file
    mov rcx, rax
    lea rdx, [input_buffer]
    mov r8, 131071               ; Max 128KB - 1
    lea r9, [input_size]
    mov qword [rsp+32], 0
    call ReadFile

    test rax, rax
    jz .error

    ; Null terminate
    mov rax, [input_size]
    lea rdi, [input_buffer]
    add rdi, rax
    mov byte [rdi], 0

    ; Close file
    mov rcx, [infile_handle]
    call CloseHandle

    mov rax, 1
    jmp .done

.error:
    xor rax, rax

.done:
    leave
    ret
