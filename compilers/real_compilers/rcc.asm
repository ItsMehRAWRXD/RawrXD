; ============================================
; PHASE 1: LEXICAL ANALYSIS
; ============================================
phase1_lexical_analysis:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    ; Show phase message
    mov rcx, -11
    call GetStdHandle
    mov rcx, rax
    lea rdx, [msg_lexing]
    mov r8, msg_lexing_len
    lea r9, [written]
    mov qword [rsp+32], 0
    call WriteFile

    ; Initialize lexer state
    lea rax, [input_buffer]
    mov [current_char], rax
    mov qword [token_count], 0
    mov qword [current_line], 1
    mov qword [current_col], 1

.lexer_loop:
    ; Get current character
    mov rsi, [current_char]
    movzx eax, byte [rsi]
    test al, al
    jz .lexer_done

    ; Track line/column
    cmp al, 10
    je .newline
    cmp al, 13
    je .carriage_return
    
    ; Skip whitespace
    cmp al, ' '
    je .skip_char
    cmp al, 9
    je .skip_char

    ; Check for comments
    cmp al, '/'
    jne .not_comment
    movzx ebx, byte [rsi+1]
    cmp bl, '/'
    je .skip_line_comment
    cmp bl, '*'
    je .skip_block_comment

.not_comment:
    ; Check for identifiers and keywords
    call is_alpha
    jc .lex_identifier
    
    ; Check for numbers
    call is_digit
    jc .lex_number
    
    ; Check for string literals
    cmp al, '"'
    je .lex_string
    cmp al, "'"
    je .lex_char
    
    ; Check for operators and symbols
    call lex_operator
    jmp .lexer_loop

.newline:
    inc qword [current_line]
    mov qword [current_col], 1
    jmp .skip_char

.carriage_return:
    jmp .skip_char

.skip_char:
    inc rsi
    inc qword [current_col]
    mov [current_char], rsi
    jmp .lexer_loop

.skip_line_comment:
    add rsi, 2
.line_comment_loop:
    movzx eax, byte [rsi]
    cmp al, 10
    je .comment_done
    test al, al
    jz .lexer_done
    inc rsi
    jmp .line_comment_loop

.skip_block_comment:
    add rsi, 2
.block_comment_loop:
    movzx eax, byte [rsi]
    test al, al
    jz .lexer_done
    cmp al, '*'
    jne .not_end_block
    movzx ebx, byte [rsi+1]
    cmp bl, '/'
    je .block_comment_done
.not_end_block:
    inc rsi
    jmp .block_comment_loop
.block_comment_done:
    add rsi, 2
    mov [current_char], rsi
    jmp .lexer_loop

.comment_done:
    mov [current_char], rsi
    jmp .lexer_loop

.lex_identifier:
    call tokenize_identifier
    jmp .lexer_loop

.lex_number:
    call tokenize_number
    jmp .lexer_loop

.lex_string:
    call tokenize_string
    jmp .lexer_loop

.lex_char:
    call tokenize_char
    jmp .lexer_loop

.lexer_done:
    ; Add EOF token
    mov rcx, TOKEN_EOF
    xor rdx, rdx
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token
    
    mov rax, 1
    leave
    ret

; ============================================
; TOKENIZE IDENTIFIER
; ============================================
tokenize_identifier:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    lea rdi, [ident_buffer]
    mov rsi, [current_char]

.copy_loop:
    movzx eax, byte [rsi]
    call is_alnum
    jnc .done_copy
    stosb
    inc rsi
    inc qword [current_col]
    jmp .copy_loop

.done_copy:
    mov byte [rdi], 0
    mov [current_char], rsi

    ; Check if it's a keyword
    lea rcx, [ident_buffer]
    call check_keyword
    test rax, rax
    jnz .is_keyword

    ; It's an identifier
    mov rcx, TOKEN_IDENT
    lea rdx, [ident_buffer]
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token
    jmp .done

.is_keyword:
    ; rax contains token type
    mov rcx, rax
    lea rdx, [ident_buffer]
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token

.done:
    leave
    ret

; ============================================
; TOKENIZE NUMBER
; ============================================
tokenize_number:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    lea rdi, [number_buffer]
    mov rsi, [current_char]

.copy_loop:
    movzx eax, byte [rsi]
    call is_digit
    jnc .check_hex
    stosb
    inc rsi
    inc qword [current_col]
    jmp .copy_loop

.check_hex:
    cmp al, 'x'
    je .hex_number
    cmp al, 'X'
    je .hex_number
    cmp al, '.'
    je .float_number
    jmp .done_copy

.hex_number:
    stosb
    inc rsi
.hex_loop:
    movzx eax, byte [rsi]
    call is_hex_digit
    jnc .done_copy
    stosb
    inc rsi
    inc qword [current_col]
    jmp .hex_loop

.float_number:
    stosb
    inc rsi
.float_loop:
    movzx eax, byte [rsi]
    call is_digit
    jnc .done_copy
    stosb
    inc rsi
    inc qword [current_col]
    jmp .float_loop

.done_copy:
    mov byte [rdi], 0
    mov [current_char], rsi

    mov rcx, TOKEN_NUMBER
    lea rdx, [number_buffer]
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token

    leave
    ret

; ============================================
; TOKENIZE STRING
; ============================================
tokenize_string:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    mov rsi, [current_char]
    inc rsi                    ; Skip opening quote
    lea rdi, [string_buffer]

.copy_loop:
    movzx eax, byte [rsi]
    test al, al
    jz .unterminated
    cmp al, '"'
    je .done_copy
    cmp al, '\\'
    je .escape_char
    stosb
    inc rsi
    inc qword [current_col]
    jmp .copy_loop

.escape_char:
    inc rsi
    movzx eax, byte [rsi]
    cmp al, 'n'
    je .esc_newline
    cmp al, 't'
    je .esc_tab
    cmp al, '\\'
    je .esc_backslash
    cmp al, '"'
    je .esc_quote
    cmp al, '0'
    je .esc_null
    ; Unknown escape, just copy as-is
    stosb
    jmp .copy_loop

.esc_newline:
    mov al, 10
    stosb
    inc rsi
    jmp .copy_loop

.esc_tab:
    mov al, 9
    stosb
    inc rsi
    jmp .copy_loop

.esc_backslash:
    mov al, '\\'
    stosb
    inc rsi
    jmp .copy_loop

.esc_quote:
    mov al, '"'
    stosb
    inc rsi
    jmp .copy_loop

.esc_null:
    mov al, 0
    stosb
    inc rsi
    jmp .copy_loop

.unterminated:
    xor rax, rax
    leave
    ret

.done_copy:
    mov byte [rdi], 0
    inc rsi                    ; Skip closing quote
    mov [current_char], rsi

    mov rcx, TOKEN_STRING
    lea rdx, [string_buffer]
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token

    mov rax, 1
    leave
    ret

; ============================================
; TOKENIZE CHARACTER
; ============================================
tokenize_char:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    mov rsi, [current_char]
    inc rsi                    ; Skip opening quote
    
    movzx eax, byte [rsi]
    cmp al, '\\'
    je .escape
    mov [string_buffer], al
    jmp .done_char

.escape:
    inc rsi
    movzx eax, byte [rsi]
    cmp al, 'n'
    je .esc_n
    cmp al, 't'
    je .esc_t
    cmp al, '0'
    je .esc_0
    mov [string_buffer], al
    jmp .done_char

.esc_n:
    mov byte [string_buffer], 10
    jmp .done_char

.esc_t:
    mov byte [string_buffer], 9
    jmp .done_char

.esc_0:
    mov byte [string_buffer], 0

.done_char:
    inc rsi                    ; Skip char
    inc rsi                    ; Skip closing quote
    mov [current_char], rsi

    mov rcx, TOKEN_NUMBER      ; Character is a number
    lea rdx, [string_buffer]
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token

    leave
    ret

; ============================================
; LEX OPERATOR
; ============================================
lex_operator:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    mov rsi, [current_char]
    movzx eax, byte [rsi]
    movzx ebx, byte [rsi+1]

    ; Two-character operators
    cmp al, '='
    jne .not_eq
    cmp bl, '='
    je .op_eq
    mov rcx, TOKEN_ASSIGN
    jmp .single_char

.not_eq:
    cmp al, '!'
    jne .not_ne
    cmp bl, '='
    je .op_ne
    mov rcx, TOKEN_NOT
    jmp .single_char

.not_ne:
    cmp al, '<'
    jne .not_lt
    cmp bl, '='
    je .op_le
    mov rcx, TOKEN_LT
    jmp .single_char

.not_lt:
    cmp al, '>'
    jne .not_gt
    cmp bl, '='
    je .op_ge
    mov rcx, TOKEN_GT
    jmp .single_char

.not_gt:
    cmp al, '&'
    jne .not_and
    cmp bl, '&'
    je .op_and
    jmp .single_char

.not_and:
    cmp al, '|'
    jne .not_or
    cmp bl, '|'
    je .op_or
    jmp .single_char

.not_or:
    ; Single character operators
    cmp al, '+'
    jne .not_plus
    mov rcx, TOKEN_PLUS
    jmp .single_char

.not_plus:
    cmp al, '-'
    jne .not_minus
    mov rcx, TOKEN_MINUS
    jmp .single_char

.not_minus:
    cmp al, '*'
    jne .not_mul
    mov rcx, TOKEN_MUL
    jmp .single_char

.not_mul:
    cmp al, '/'
    jne .not_div
    mov rcx, TOKEN_DIV
    jmp .single_char

.not_div:
    cmp al, '('
    jne .not_lparen
    mov rcx, TOKEN_LPAREN
    jmp .single_char

.not_lparen:
    cmp al, ')'
    jne .not_rparen
    mov rcx, TOKEN_RPAREN
    jmp .single_char

.not_rparen:
    cmp al, '{'
    jne .not_lbrace
    mov rcx, TOKEN_LBRACE
    jmp .single_char

.not_lbrace:
    cmp al, '}'
    jne .not_rbrace
    mov rcx, TOKEN_RBRACE
    jmp .single_char

.not_rbrace:
    cmp al, ';'
    jne .not_semi
    mov rcx, TOKEN_SEMI
    jmp .single_char

.not_semi:
    cmp al, ','
    jne .not_comma
    mov rcx, TOKEN_COMMA
    jmp .single_char

.not_comma:
    ; Unknown character, skip it
    inc rsi
    mov [current_char], rsi
    inc qword [current_col]
    jmp .done

.op_eq:
    mov rcx, TOKEN_EQ
    add rsi, 2
    jmp .add_op

.op_ne:
    mov rcx, TOKEN_NE
    add rsi, 2
    jmp .add_op

.op_le:
    mov rcx, TOKEN_LE
    add rsi, 2
    jmp .add_op

.op_ge:
    mov rcx, TOKEN_GE
    add rsi, 2
    jmp .add_op

.op_and:
    mov rcx, TOKEN_AND
    add rsi, 2
    jmp .add_op

.op_or:
    mov rcx, TOKEN_OR
    add rsi, 2
    jmp .add_op

.single_char:
    inc rsi

.add_op:
    mov [current_char], rsi
    xor rdx, rdx
    mov r8, [current_line]
    mov r9, [current_col]
    call add_token
    inc qword [current_col]

.done:
    leave
    ret

; ============================================
; ADD TOKEN
; ============================================
add_token:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    ; rcx = token type
    ; rdx = token text pointer (or 0)
    ; r8 = line
    ; r9 = column

    mov r10, [token_count]
    cmp r10, 8192
    jae .overflow

    ; Calculate token address: tokens + (r10 * 24)
    mov r11, r10
    shl r11, 4          ; * 16
    mov rax, r10
    shl rax, 3          ; * 8
    add r11, rax        ; r11 = r10 * 24
    lea rdi, [tokens + r11]

    ; Store token type
    mov [rdi], ecx

    ; Store text pointer (copy to token_buffer if needed)
    test rdx, rdx
    jz .no_text
    
    ; Calculate offset in token_buffer
    mov rax, [token_count]
    imul rax, 32        ; Each token gets 32 bytes for text
    lea rdi, [token_buffer + rax]
    mov rsi, rdx
.copy_text:
    lodsb
    stosb
    test al, al
    jnz .copy_text

    mov r11, [token_count]
    shl r11, 4
    mov rax, [token_count]
    shl rax, 3
    add r11, rax
    lea rdi, [tokens + r11]
    mov rax, [token_count]
    imul rax, 32
    lea rax, [token_buffer + rax]
    mov [rdi+8], rax

.no_text:
    ; Store line and column
    mov [rdi+16], r8d
    mov [rdi+20], r9d

    inc qword [token_count]
    mov rax, 1
    jmp .done

.overflow:
    xor rax, rax

.done:
    leave
    ret

; ============================================
; CHECK KEYWORD
; ============================================
check_keyword:
    push rbp
    mov rbp, rsp
    sub rsp, 128

    ; rcx = string to check
    mov rsi, rcx

    ; Check "int"
    lea rdi, [kw_int]
    call strcmp
    test rax, rax
    jz .not_int
    mov rax, TOKEN_INT
    jmp .done
.not_int:

    ; Check "char"
    lea rdi, [kw_char]
    call strcmp
    test rax, rax
    jz .not_char
    mov rax, TOKEN_CHAR
    jmp .done
.not_char:

    ; Check "void"
    lea rdi, [kw_void]
    call strcmp
    test rax, rax
    jz .not_void
    mov rax, TOKEN_VOID
    jmp .done
.not_void:

    ; Check "return"
    lea rdi, [kw_return]
    call strcmp
    test rax, rax
    jz .not_return
    mov rax, TOKEN_RETURN
    jmp .done
.not_return:

    ; Check "if"
    lea rdi, [kw_if]
    call strcmp
    test rax, rax
    jz .not_if
    mov rax, TOKEN_IF
    jmp .done
.not_if:

    ; Check "else"
    lea rdi, [kw_else]
    call strcmp
    test rax, rax
    jz .not_else
    mov rax, TOKEN_KEYWORD
    jmp .done
.not_else:

    ; Check "while"
    lea rdi, [kw_while]
    call strcmp
    test rax, rax
    jz .not_while
    mov rax, TOKEN_WHILE
    jmp .done
.not_while:

    ; Check "for"
    lea rdi, [kw_for]
    call strcmp
    test rax, rax
    jz .not_for
    mov rax, TOKEN_FOR
    jmp .done
.not_for:

    xor rax, rax

.done:
    leave
    ret

; ============================================
; STRING COMPARE
; ============================================
strcmp:
    push rbp
    mov rbp, rsp

.loop:
    mov al, [rsi]
    mov bl, [rdi]
    cmp al, bl
    jne .not_equal
    test al, al
    jz .equal
    inc rsi
    inc rdi
    jmp .loop

.not_equal:
    xor rax, rax
    leave
    ret

.equal:
    mov rax, 1
    leave
    ret

; ============================================
; CHARACTER CLASSIFICATION
; ============================================
is_alpha:
    cmp al, 'A'
    jb .not
    cmp al, 'Z'
    jbe .yes
    cmp al, 'a'
    jb .not
    cmp al, 'z'
    jbe .yes
    cmp al, '_'
    je .yes
.not:
    clc
    ret
.yes:
    stc
    ret

is_digit:
    cmp al, '0'
    jb .not
    cmp al, '9'
    ja .not
    stc
    ret
.not:
    clc
    ret

is_alnum:
    call is_alpha
    jc .yes
    call is_digit
    ret
.yes:
    stc
    ret

is_hex_digit:
    call is_digit
    jc .yes
    cmp al, 'a'
    jb .check_upper
    cmp al, 'f'
    jbe .yes
.check_upper:
    cmp al, 'A'
    jb .not
    cmp al, 'F'
    jbe .yes
.not:
    clc
    ret
.yes:
    stc
    ret

