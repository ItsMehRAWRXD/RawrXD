// c_ast_lower.cpp — the C11 tree lowered to x64 assembly.
//
// The input is the tree of the certified C11 parser. The output is the
// assembly the certified first-party assembler reads.
//
// ---------------------------------------------------------------------------
// The frame
// ---------------------------------------------------------------------------
//
// Win64. A function keeps its arguments, its locals and its temporaries in
// its frame, and the frame reserves 32 bytes of shadow space at its bottom
// for the calls it makes. The frame size is a multiple of 16, so the stack
// is aligned at every call.
//
// A function with no locals, no parameters and no temporaries needs no frame
// pointer at all. It still reserves the shadow space, and the stack still has
// to be aligned at a call, so it reserves 32 bytes of shadow space plus 8
// bytes of alignment.
//
// ---------------------------------------------------------------------------
// The temporaries
// ---------------------------------------------------------------------------
//
// A binary operation keeps its left operand in a frame slot rather than on
// the stack, so the stack pointer never moves inside a body. That is what
// keeps the alignment the ABI requires intact: a push and a pop around a
// call would leave the stack misaligned by eight bytes.

#include "frontend/c_ast_lower.h"

#include "common/Diagnostics.h"
#include "common/SourceManager.h"
#include "frontend/AST.h"
#include "frontend/Parser.h"
#include "frontend/Preprocessor.h"
#include "frontend/Token.h"

#include "rawrstd/string.h"
#include "rawrstd/sys.h"
