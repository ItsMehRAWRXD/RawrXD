bool c_ast_compile_to_asm(const char* source_path, const char* asm_path,
                           String* error) {
    if (!source_path || !asm_path || !error) return false;
    error->clear();

    // Read the source.
    String source;
    {
        rawrstd::File in;
        if (!in.open(source_path, rawrstd::FileMode::Read)) {
            *error = String("cannot open ") + String(source_path);
            return false;
        }
        char buffer[8192];
        for (;;) {
            const long long got = in.read(buffer, sizeof(buffer));
            if (got <= 0) break;
            source.append(buffer, static_cast<size_type>(got));
        }
        in.close();
    }

    SourceManager sources;
    DiagnosticEngine diags(&sources);
    const uint32 file_id = sources.add_buffer(source_path, source.data(), source.size());

    // The certified preprocessor and the certified parser.
    Preprocessor preprocessor(&sources, &diags);
    Vector<Token> tokens;
    if (!preprocessor.run(file_id, &tokens)) {
        *error = diags.render();
        if (error->empty()) *error = String("the preprocessor failed");
        return false;
    }

    AST ast;
    Parser parser(&sources, &diags, &ast);
    if (!parser.parse_translation_unit(tokens) || parser.error_count() > 0) {
        *error = diags.render();
        if (error->empty()) *error = String("the source could not be parsed");
        return false;
    }

    // Lower the tree.
    String assembly;
    Lowerer lowerer(&assembly);
    if (!lowerer.lower(parser.translation_unit())) {
        *error = lowerer.diagnostics();
        if (error->empty()) *error = String("the source could not be lowered");
        return false;
    }

    rawrstd::File out;
    if (!out.open(asm_path, rawrstd::FileMode::Write)) {
        *error = String("cannot write ") + String(asm_path);
        return false;
    }
    out.write(assembly.data(), assembly.size());
    out.close();
    return true;
}

