<#
    update_manifest.ps1 - regenerates the stage 1 certification manifest.

    The manifest is the pin between a green certification result and the
    source revision that produced it. It lists every source file in the tree
    with its SHA-256, and every object file the certification build produces
    with the source it comes from.

    Regenerate it after any source change, and commit the result. The C09
    gate then fails if the tree moves away from the recorded revision, or if
    an object file is older than a source file, which is what a stale or
    partial build looks like.

    Usage:
        powershell -File tools\update_manifest.ps1
        powershell -File tools\update_manifest.ps1 -Out <output dir>
#>
param(
    [string]$Root = (Join-Path $PSScriptRoot '..'),
    [string]$Out  = (Join-Path $PSScriptRoot '..\..\build\rawr_stage1')
)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path $Root).Path
if (-not (Test-Path $Out)) {
    Write-Error "output directory not found: $Out"
    exit 1
}
$Out = (Resolve-Path $Out).Path

# The hash of a source file, with the line endings normalized.
#
# Git stores a file with the line endings of the repository and checks it
# out with the line endings of the platform, so the same file has a
# different byte sequence in a working tree and in an exported tree. The
# hash has to be the same in both places, or the gate would fail in an
# exported tree even though nothing was changed.
function Get-NormalizedHash([string]$Path) {
    $bytes = [System.IO.File]::ReadAllBytes($Path)
    $normalized = New-Object System.Collections.Generic.List[byte]
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($bytes[$i] -eq 13 -and ($i + 1) -lt $bytes.Length -and $bytes[$i + 1] -eq 10) { continue }
        $normalized.Add($bytes[$i])
    }
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hash = $sha.ComputeHash($normalized.ToArray())
    return ([System.BitConverter]::ToString($hash)).Replace('-', '').ToLower()
}
# Every file the compiler is built from.
$sourceExtensions = @('.cpp', '.h', '.hpp', '.c')
$sources = Get-ChildItem -Path $Root -Recurse -File |
    Where-Object { $sourceExtensions -contains $_.Extension.ToLower() } |
    Sort-Object FullName

# Map a source file name to its path, so an object can be traced back.
# A name can appear more than once, because a header and a source file
# share it. The source file wins, because that is what is compiled.
$byBaseName = @{}
foreach ($s in $sources) {
    if ($s.Extension -eq '.cpp' -or $s.Extension -eq '.c') {
        $byBaseName[$s.BaseName] = $s
    }
}
foreach ($s in $sources) {
    if (-not $byBaseName.ContainsKey($s.BaseName)) {
        $byBaseName[$s.BaseName] = $s
    }
}

# The objects the certification build produces. The object name is the
# source file name with the extension changed, which is what cl does.
#
# These are the only translation units the stage 1 build compiles. The
# diagnostics and the helper programs are built by their own scripts and
# are not part of the certification.
$compiledSources = @(
    'rawrstd/src/sys.cpp',
    'rawrstd/src/string.cpp',
    'rawrstd/src/sha256.cpp',
    'src/common/SourceManager.cpp',
    'src/common/Diagnostics.cpp',
    'src/frontend/Token.cpp',
    'src/frontend/Lexer.cpp',
    'src/frontend/Preprocessor.cpp',
    'src/frontend/AST.cpp',
    'src/frontend/Parser.cpp',
    'src/object/CoffWriter.cpp',
    'src/asm/X64Assembler.cpp',
    'tests/c01_lexer_test.cpp',
    'tests/c02_coff_writer_test.cpp',
    'tests/c03_e2e_test.cpp',
    'tests/c04_multi_object_test.cpp',
    'tests/c05_reloc_import_test.cpp',
    'tests/c06_dll_test.cpp',
    'tests/c07_e2e_test.cpp',
    'tests/c08_negative_test.cpp',
    'tests/c09_provenance_test.cpp',
    'tests/c10_preprocessor_test.cpp',
    'tests/c11_parser_test.cpp'
)

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# RawrXD stage 1 certification manifest')
$lines.Add('#')
$lines.Add('# Generated by tools\update_manifest.ps1. Commit this file: it pins the')
$lines.Add('# certification result to one specific source revision. The C09 gate')
$lines.Add('# fails when the tree moves away from these hashes, or when an object')
$lines.Add('# file is older than a source file.')
$lines.Add('#')
$lines.Add('# source <sha256> <path relative to native_compiler>')
$lines.Add('# object <object file name> <path relative to native_compiler>')
$lines.Add('')

$missing = New-Object System.Collections.Generic.List[string]
foreach ($s in $sources) {
    $relative = $s.FullName.Substring($Root.Length).TrimStart('\', '/') -replace '\\', '/'
    $hash = Get-NormalizedHash $s.FullName
    $lines.Add("source $hash $relative")
}
$lines.Add('')

$objectCount = 0
foreach ($relative in $compiledSources) {
    $sourcePath = Join-Path $Root ($relative -replace '/', '\')
    if (-not (Test-Path $sourcePath)) {
        $missing.Add($relative)
        continue
    }
    $objectName = [System.IO.Path]::GetFileNameWithoutExtension($relative) + '.obj'
    if (-not (Test-Path (Join-Path $Out $objectName))) {
        $missing.Add("$objectName (not built)")
        continue
    }
    $lines.Add("object $objectName $relative")
    $objectCount++
}

$manifestPath = Join-Path $Root 'tools\certification_manifest.txt'
[System.IO.File]::WriteAllLines($manifestPath, $lines)

Write-Output ("manifest: {0}" -f $manifestPath)
Write-Output ("  sources: {0}" -f $sources.Count)
Write-Output ("  objects: {0}" -f $objectCount)
if ($missing.Count -gt 0) {
    Write-Output ("  WARNING: {0}" -f ($missing -join ', '))
}
