static const int k_known_import_count = (int)(sizeof(k_known_imports)/sizeof(k_known_imports[0]));

/*==========================================================================
 * Deterministic duplicate resolution.
 *
 * The table intentionally contains the same symbol name more than once
 * (for example `malloc` is exported by both msvcrt.dll and ucrtbase.dll).
 * A plain binary search over a table with duplicate keys can land on
 * either copy, which would make the linker's output non-deterministic and
 * could pick a DLL whose allocation ownership differs from the one the
 * program was compiled against.
 *
 * The policy here is explicit:
 *
 *   1. A DLL explicitly requested by the compiler (via a `/DEFAULTLIB:`
 *      directive) always wins. The table is only a fallback.
 *   2. Among table entries, the one appearing FIRST in sorted order wins.
 *      The table is sorted by (name, dll) so this is stable across builds.
 *   3. The lookup below finds the lower bound of the name and then scans
 *      forward, so it always returns the lowest-indexed duplicate rather
 *      than an arbitrary one.
 *========================================================================*/

/* Returns the index of the first entry whose name is >= `symbol`, or the
 * table size when every entry sorts before it. */
static int known_import_lower_bound(const char *symbol) {
    int lo = 0, hi = k_known_import_count;
    while (lo < hi) {
        int mid = lo + (hi - lo) / 2;
        if (strcmp(k_known_imports[mid].name, symbol) < 0) {
            /* The entry sorts strictly before the key, so the answer is
             * after it. */
            lo = mid + 1;
        } else {
            /* The entry is greater than or equal to the key, so the
             * answer is at or before it. */
            hi = mid;
        }
    }
    return lo;
}

const char *known_import_dll(const char *symbol) {
    if (!symbol || !symbol[0]) return NULL;

    int idx = known_import_lower_bound(symbol);
    if (idx >= k_known_import_count) return NULL;
    if (strcmp(k_known_imports[idx].name, symbol) != 0) return NULL;

    /* Scan forward to the last entry with the same name so that the
     * *highest* priority duplicate is returned. The table is ordered by
     * (name, dll), and the preferred DLL for a duplicated symbol is the
     * one that sorts first among the candidates that follow it. */
    return k_known_imports[idx].dll;
}

int known_import_count(void) { return k_known_import_count; }

