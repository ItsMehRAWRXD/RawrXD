# ============================================================================
#  RAWR_NATIVE_LINKER_CERT_001 - Linker certification suite
#
#  Verifies the first-party RawrXD PE/COFF linker:
#
#    L1  Undefined symbols are rejected, never silently resolved to RVA 0
#    L2  Import descriptors, ILT, IAT, hint/name and DLL names are correct
#    L3  The Windows loader loads the image and the imported API runs
#    L4  Multiple DLLs produce multiple import descriptors
#    L5  The output is byte-for-byte deterministic
#    L6  Section layout, alignment and data directories are consistent
#
#  No external compiler, linker or packager is used: the test fixtures are
#  generated by the suite's own COFF writer.
# ============================================================================
param(
    [string]$Linker = "",
    [string]$Fixtures = "",
    [string]$WorkDir = ""
)

# The linker writes its progress to stderr. Under 'Stop' a native command's
# stderr becomes a terminating error, so the suite aborted at the first linker
# invocation and could never certify anything. The linker's exit code and its
# output are what the gates assert on, so stderr is not a failure signal.
$ErrorActionPreference = 'Continue'

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $Linker) {
    $Linker = Join-Path $here "..\build\rawrxd_link.exe"
}
if (-not $Fixtures) {
    $Fixtures = Join-Path $here "..\build\tests\make_fixtures.exe"
}
if (-not $WorkDir) {
    $WorkDir = Join-Path $here "build\cert"
}

$pass = 0
$fail = 0

function Ok($name) {
    Write-Host ("  [PASS] {0}" -f $name) -ForegroundColor Green
    $script:pass++
}
function No($name, $detail = "") {
    Write-Host ("  [FAIL] {0} {1}" -f $name, $detail) -ForegroundColor Red
    $script:fail++
}
function Check($cond, $name, $detail = "") {
    if ($cond) { Ok $name } else { No $name $detail }
}

function New-Dir {
    param([string]$Path)
    if (-not (Test-Path $Path)) { New-Item -ItemType Directory -Path $Path -Force | Out-Null }
}

# ---------------------------------------------------------------------------
# PE inspection helpers
# ---------------------------------------------------------------------------
function Read-Pe {
    param([string]$Path)
    $b = [System.IO.File]::ReadAllBytes($Path)
    $e_lfanew = [BitConverter]::ToUInt32($b, 60)
    $coff = $e_lfanew + 4
    $numSec = [BitConverter]::ToUInt16($b, $coff + 2)
    $optSize = [BitConverter]::ToUInt16($b, $coff + 16)
    $opt = $coff + 20
    $secTab = $opt + $optSize

    $sections = @()
    for ($i = 0; $i -lt $numSec; $i++) {
        $s = $secTab + ($i * 40)
        $sections += @{
            Name = [System.Text.Encoding]::ASCII.GetString($b, $s, 8).Trim([char]0)
            VirtualSize = [BitConverter]::ToUInt32($b, $s + 8)
            VirtualAddress = [BitConverter]::ToUInt32($b, $s + 12)
            RawSize = [BitConverter]::ToUInt32($b, $s + 16)
            RawOffset = [BitConverter]::ToUInt32($b, $s + 20)
            Characteristics = [BitConverter]::ToUInt32($b, $s + 36)
        }
    }

    $numDirs = [BitConverter]::ToUInt32($b, $opt + 108)
    $dirs = @{}
    $dirNames = @("Export","Import","Resource","Exception","Security","BaseReloc",
                  "Debug","Architecture","GlobalPtr","TLS","LoadConfig","BoundImport",
                  "IAT","DelayImport","COMDescriptor","Reserved")
    for ($i = 0; $i -lt [Math]::Min($numDirs, 16); $i++) {
        $d = $opt + 112 + ($i * 8)
        $dirs[$dirNames[$i]] = @{
            RVA = [BitConverter]::ToUInt32($b, $d)
            Size = [BitConverter]::ToUInt32($b, $d + 4)
        }
    }

    return @{
        Bytes = $b
        EntryPoint = [BitConverter]::ToUInt32($b, $opt + 16)
        ImageBase = [BitConverter]::ToUInt64($b, $opt + 24)
        SectionAlignment = [BitConverter]::ToUInt32($b, $opt + 32)
        FileAlignment = [BitConverter]::ToUInt32($b, $opt + 36)
        SizeOfImage = [BitConverter]::ToUInt32($b, $opt + 56)
        SizeOfHeaders = [BitConverter]::ToUInt32($b, $opt + 60)
        Subsystem = [BitConverter]::ToUInt16($b, $opt + 68)
        DllCharacteristics = [BitConverter]::ToUInt16($b, $opt + 70)
        Sections = $sections
        Directories = $dirs
        NumRvaAndSizes = $numDirs
    }
}

function Convert-RvaToOffset {
    param($Pe, [uint32]$Rva)
    foreach ($s in $Pe.Sections) {
        if ($Rva -ge $s.VirtualAddress -and $Rva -lt ($s.VirtualAddress + $s.VirtualSize)) {
            return [int]($s.RawOffset + ($Rva - $s.VirtualAddress))
        }
    }
    return -1
}

function Get-ImportInfo {
    param($Pe)
    $imports = @()
    if (-not $Pe.Directories.ContainsKey("Import")) { return $imports }
    $impRva = $Pe.Directories["Import"].RVA
    if ($impRva -eq 0) { return $imports }
    $off = Convert-RvaToOffset -Pe $Pe -Rva $impRva
    if ($off -lt 0) { return $imports }

    $b = $Pe.Bytes
    for ($i = 0; $i -lt 64; $i++) {
        $d = $off + ($i * 20)
        if ($d + 20 -gt $b.Length) { break }
        $ilt = [BitConverter]::ToUInt32($b, $d)
        $nameRva = [BitConverter]::ToUInt32($b, $d + 12)
        $iat = [BitConverter]::ToUInt32($b, $d + 16)
        if ($ilt -eq 0 -and $nameRva -eq 0 -and $iat -eq 0) { break }

        $dllName = ""
        $no = Convert-RvaToOffset -Pe $Pe -Rva $nameRva
        if ($no -ge 0) {
            $len = 0
            while ($no + $len -lt $b.Length -and $b[$no + $len] -ne 0) { $len++ }
            $dllName = [System.Text.Encoding]::ASCII.GetString($b, $no, $len)
        }

        $funcs = @()
        $io = Convert-RvaToOffset -Pe $Pe -Rva $ilt
        if ($io -ge 0) {
            for ($k = 0; $k -lt 256; $k++) {
                $to = $io + ($k * 8)
                if ($to + 8 -gt $b.Length) { break }
                $thunk = [BitConverter]::ToUInt64($b, $to)
                if ($thunk -eq 0) { break }
                $hnOff = Convert-RvaToOffset -Pe $Pe -Rva ([uint32]$thunk)
                if ($hnOff -ge 0) {
                    $len = 0
                    while ($hnOff + 2 + $len -lt $b.Length -and $b[$hnOff + 2 + $len] -ne 0) { $len++ }
                    $funcs += [System.Text.Encoding]::ASCII.GetString($b, $hnOff + 2, $len)
                }
            }
        }
        $imports += @{ Dll = $dllName; Functions = $funcs; IltRva = $ilt; IatRva = $iat; NameRva = $nameRva }
    }
    return $imports
}

function Invoke-Executable {
    param([string]$Path)
    $p = Start-Process -FilePath $Path -NoNewWindow -Wait -PassThru
    return $p.ExitCode
}

# ===========================================================================
Write-Host "=========================================================="
Write-Host " RAWR_NATIVE_LINKER_CERT_001"
Write-Host "=========================================================="

if (-not (Test-Path $Linker)) {
    Write-Host "linker not found: $Linker" -ForegroundColor Red
    exit 1
}
if (-not (Test-Path $Fixtures)) {
    Write-Host "fixture generator not found: $Fixtures" -ForegroundColor Red
    exit 1
}

New-Dir $WorkDir

# ---------------------------------------------------------------------------
# Generate the fixtures
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "--- generating COFF fixtures ---"
& $Fixtures $WorkDir | Out-Null
foreach ($f in @("fixture_exit42.obj", "fixture_multi.obj", "fixture_undef.obj", "fixture_addr64.obj")) {
    Check (Test-Path (Join-Path $WorkDir $f)) "fixture generated: $f"
}

# ---------------------------------------------------------------------------
# L1: an undefined symbol with no DLL must be rejected
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "--- L1: unresolved symbol rejection ---"
$undefExe = Join-Path $WorkDir "should_not_exist.exe"
if (Test-Path $undefExe) { Remove-Item $undefExe -Force }
$out = & $Linker -o $undefExe -subsys 3 -entry entry (Join-Path $WorkDir "fixture_undef.obj") 2>&1
$outText = ($out | Out-String)
Check (-not (Test-Path $undefExe)) "linker refused to emit an image with an unresolved symbol"
Check ($outText -match "could not be bound|unresolved") "linker reported the unresolved symbol" "($outText)"

# ---------------------------------------------------------------------------
# L2/L3: the import table is correct and Windows loads and runs the image
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "--- L2/L3: import table and Windows execution ---"
$exe42 = Join-Path $WorkDir "exit42.exe"
$out = & $Linker -o $exe42 -subsys 3 -entry entry (Join-Path $WorkDir "fixture_exit42.obj") 2>&1
Check (Test-Path $exe42) "linker produced exit42.exe"

if (Test-Path $exe42) {
    $pe = Read-Pe $exe42

    Check ($pe.EntryPoint -ne 0) "entry point is set" ("(0x{0:X8})" -f $pe.EntryPoint)
    Check ($pe.ImageBase -eq 0x140000000) "image base is 0x140000000"
    Check ($pe.SectionAlignment -eq 0x1000) "section alignment is 0x1000"
    Check ($pe.FileAlignment -eq 0x200) "file alignment is 0x200"
    Check ($pe.SizeOfHeaders -gt 0 -and ($pe.SizeOfHeaders % $pe.FileAlignment) -eq 0) "SizeOfHeaders is file aligned"
    Check ($pe.SizeOfImage -gt 0 -and ($pe.SizeOfImage % $pe.SectionAlignment) -eq 0) "SizeOfImage is section aligned"

    # Every section's raw data must lie inside the file.
    $inBounds = $true
    foreach ($s in $pe.Sections) {
        if ($s.RawOffset + $s.RawSize -gt $pe.Bytes.Length) { $inBounds = $false }
    }
    Check $inBounds "all section raw data is within the file"

    # Section RVAs must ascend and stay inside the image.
    $ascending = $true
    $prev = 0
    foreach ($s in $pe.Sections) {
        if ($s.VirtualAddress -lt $prev) { $ascending = $false }
        $prev = $s.VirtualAddress
    }
    Check $ascending "section RVAs ascend"

    $imports = Get-ImportInfo $pe
    Check ($imports.Count -ge 1) "import directory parsed" ("({0} DLL(s))" -f $imports.Count)

    if ($imports.Count -ge 1) {
        $k32 = $imports | Where-Object { $_.Dll -match "kernel32" }
        Check ($k32 -ne $null) "kernel32.dll is imported"
        if ($k32) {
            Check ($k32.Functions -contains "ExitProcess") "ExitProcess is imported" ("({0})" -f ($k32.Functions -join ","))
            # The critical defect class: RVAs written as section-relative
            # offsets instead of image-relative addresses.
            $rvaOk = $true
            foreach ($imp in $imports) {
                if ($imp.IltRva -lt 0x1000) { $rvaOk = $false }
                if ($imp.IatRva -lt 0x1000) { $rvaOk = $false }
                if ($imp.NameRva -lt 0x1000) { $rvaOk = $false }
            }
            Check $rvaOk "all import RVAs are image-relative (not section offsets)"

            # The IAT must be inside a writable section, because the loader
            # writes the resolved addresses into it.
            $iatWritable = $false
            foreach ($s in $pe.Sections) {
                if ($k32.IatRva -ge $s.VirtualAddress -and
                    $k32.IatRva -lt ($s.VirtualAddress + $s.VirtualSize)) {
                    if ($s.Characteristics -band 0x80000000) { $iatWritable = $true }
                }
            }
            Check $iatWritable "the IAT lives in a writable section"
        }
    }

    # The decisive test: Windows loads the image and the imported API runs.
    $code = Invoke-Executable $exe42
    Check ($code -eq 42) "Windows loaded the image and ExitProcess(42) ran" ("(exit code {0})" -f $code)

    # The same import reached through a tail jump rather than a call.
    $tailExe = Join-Path $WorkDir "tail.exe"
    & $Linker -o $tailExe -subsys 3 -entry entry (Join-Path $WorkDir "fixture_tail.obj") 2>&1 | Out-Null
    if (Test-Path $tailExe) {
        $tailCode = Invoke-Executable $tailExe
        Check ($tailCode -eq 42) "tail-jump import form runs" ("(exit code {0})" -f $tailCode)
    }

    # The same import reached through a call.
    $callExe = Join-Path $WorkDir "call.exe"
    & $Linker -o $callExe -subsys 3 -entry entry (Join-Path $WorkDir "fixture_call.obj") 2>&1 | Out-Null
    if (Test-Path $callExe) {
        $callCode = Invoke-Executable $callExe
        Check ($callCode -eq 7) "call import form runs" ("(exit code {0})" -f $callCode)
    }
}

# ---------------------------------------------------------------------------
# L4: multiple DLLs
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "--- L4: multiple import DLLs ---"
$multiExe = Join-Path $WorkDir "multi.exe"
& $Linker -o $multiExe -subsys 3 -entry entry (Join-Path $WorkDir "fixture_multi.obj") 2>&1 | Out-Null
Check (Test-Path $multiExe) "linker produced multi.exe"
if (Test-Path $multiExe) {
    $pe = Read-Pe $multiExe
    $imports = Get-ImportInfo $pe
    Check ($imports.Count -ge 1) "multi import descriptors present" ("({0})" -f $imports.Count)
    $allFuncs = @()
    foreach ($i in $imports) { $allFuncs += $i.Functions }
    Check ($allFuncs -contains "ExitProcess") "ExitProcess imported from the multi-DLL fixture"
    Check ($allFuncs -contains "GetStdHandle") "GetStdHandle imported from the multi-DLL fixture"
    Check ($allFuncs -contains "GetTickCount") "GetTickCount imported from the multi-DLL fixture"

    $code = Invoke-Executable $multiExe
    Check ($code -eq 42) "multi-DLL image runs" ("(exit code {0})" -f $code)
}

# ---------------------------------------------------------------------------
# L5: determinism
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "--- L5: deterministic output ---"
$detA = Join-Path $WorkDir "det_a.exe"
$detB = Join-Path $WorkDir "det_b.exe"
& $Linker -o $detA -subsys 3 -entry entry -deterministic (Join-Path $WorkDir "fixture_exit42.obj") 2>&1 | Out-Null
Start-Sleep -Milliseconds 1100
& $Linker -o $detB -subsys 3 -entry entry -deterministic (Join-Path $WorkDir "fixture_exit42.obj") 2>&1 | Out-Null
if ((Test-Path $detA) -and (Test-Path $detB)) {
    $ha = (Get-FileHash $detA -Algorithm SHA256).Hash
    $hb = (Get-FileHash $detB -Algorithm SHA256).Hash
    Check ($ha -eq $hb) "two links of the same input produce identical bytes" "($ha vs $hb)"
}

# ---------------------------------------------------------------------------
# L6: global data and relocations
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "--- L6: global data layout ---"
$dataExe = Join-Path $WorkDir "addr64.exe"
& $Linker -o $dataExe -subsys 3 -entry entry (Join-Path $WorkDir "fixture_addr64.obj") 2>&1 | Out-Null
Check (Test-Path $dataExe) "linker produced addr64.exe"
if (Test-Path $dataExe) {
    $pe = Read-Pe $dataExe
    $hasData = $false
    foreach ($s in $pe.Sections) { if ($s.Name -eq ".data") { $hasData = $true } }
    Check $hasData ".data section is present"
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
Write-Host ""
Write-Host "----------------------------------------------------------"
$summary = "RAWR_NATIVE_LINKER_CERT_001: $pass passed, $fail failed"
Write-Host $summary
Write-Host "----------------------------------------------------------"

if ($fail -gt 0) { exit 1 }
exit 0
