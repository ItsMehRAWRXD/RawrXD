#!/usr/bin/env python3
"""Generate the Win32 chat model-route table from config/chat_model_routes.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


KINDS = {"LocalFile", "Ollama", "KiloFree"}
RUNTIMES = {"native-agent", "ollama-http", "cloud-api"}


def cpp_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def render(manifest_path: Path) -> str:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema_version") != 1:
        raise ValueError("schema_version must be 1")
    routes = manifest.get("routes")
    if not isinstance(routes, list) or not routes:
        raise ValueError("routes must be a non-empty array")

    route_ids: set[str] = set()
    kinds: set[str] = set()
    for route in routes:
        if not isinstance(route, dict):
            raise ValueError("each route must be an object")
        for key in ("id", "kind", "breadcrumb", "runtime", "discovery", "model_id", "auth_env"):
            if not isinstance(route.get(key), str) or not route[key]:
                if key == "auth_env" and route.get(key) == "":
                    continue
                raise ValueError(f"route is missing a non-empty {key}")
        if route["id"] in route_ids:
            raise ValueError(f"duplicate route id: {route['id']}")
        if route["kind"] not in KINDS:
            raise ValueError(f"unsupported route kind: {route['kind']}")
        if route["runtime"] not in RUNTIMES:
            raise ValueError(f"unsupported runtime: {route['runtime']}")
        route_ids.add(route["id"])
        kinds.add(route["kind"])

    if kinds != KINDS:
        raise ValueError("manifest must define LocalFile, Ollama, and KiloFree routes")

    rows = []
    for route in routes:
        display_name = route.get("display_name", "")
        rows.append(
            "    {RouteKind::%s, %s, %s, %s, %s, %s, %s" % (
                route["kind"],
                cpp_string(route["id"]),
                cpp_string(route["breadcrumb"]),
                cpp_string(route["runtime"]),
                cpp_string(route["discovery"]),
                cpp_string(route["model_id"]),
                cpp_string(route.get("auth_env", "")),
            )
            + ", " + cpp_string(display_name) + "},"
        )

    return """// Generated by scripts/generate_chat_route_menu.py; do not edit.
#pragma once

#include <cstddef>

namespace RawrXD::ChatRouteMenu {
enum class RouteKind { LocalFile, Ollama, KiloFree };
struct RouteDescriptor {
    RouteKind kind;
    const char* id;
    const char* breadcrumb;
    const char* runtime;
    const char* discovery;
    const char* modelId;
    const char* authEnv;
    const char* displayName;
};
inline constexpr RouteDescriptor kRoutes[] = {
%s
};
inline constexpr std::size_t kRouteCount = sizeof(kRoutes) / sizeof(kRoutes[0]);

inline constexpr const RouteDescriptor* find(RouteKind kind) {
    for (const auto& route : kRoutes) {
        if (route.kind == kind) return &route;
    }
    return nullptr;
}
} // namespace RawrXD::ChatRouteMenu
""" % "\n".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    try:
        output = render(args.manifest)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="utf-8", newline="\n")
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"chat route generation failed: {exc}", file=sys.stderr)
        return 1
    print(f"generated {args.output} from {args.manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
