#requires -Version 5.1
<#
.SYNOPSIS
  Generates config/env_inventory.json and docs/ENVIRONMENT_VARIABLES.md from
  the authoritative RAWRXD_* definitions in source (M-CFG-05).
#>
[CmdletBinding()]
param(
    [string]$Root,
    [string]$InventoryPath,
    [string]$DocPath
)
$ErrorActionPreference = 'Stop'
if (-not $Root) {
    $Root = if ($PSScriptRoot) { Split-Path $PSScriptRoot -Parent } else { (Get-Location).Path }
}
if (-not $InventoryPath) { $InventoryPath = Join-Path $Root 'config\env_inventory.json' }
if (-not $DocPath) { $DocPath = Join-Path $Root 'docs\ENVIRONMENT_VARIABLES.md' }

$roots = @('src', 'include', 'tools', 'tests') | ForEach-Object { Join-Path $Root $_ } | Where-Object { Test-Path $_ }
$files = foreach ($r in $roots) { Get-ChildItem -LiteralPath $r -Recurse -File -Include *.cpp,*.h,*.hpp,*.c,*.cc,*.cxx -ErrorAction SilentlyContinue }
$names = New-Object System.Collections.Generic.HashSet[string]
foreach ($f in $files) {
    $text = Get-Content -LiteralPath $f.FullName -Raw -ErrorAction SilentlyContinue
    if (-not $text) { continue }
    foreach ($m in [regex]::Matches($text, 'RAWRXD_[A-Z0-9_]+')) { [void]$names.Add($m.Value) }
}

$knownConfigMap = @{
    'RAWRXD_HOME' = 'applicationRoot'
    'RAWRXD_CONFIG_DIR' = 'configDir'
    'RAWRXD_CACHE_DIR' = 'cacheDir'
    'RAWRXD_LOG_DIR' = 'logDir'
    'RAWRXD_MODELS_DIR' = 'modelDir'
    'RAWRXD_ALLOW_GPU' = 'features.vulkanCompute'
    'RAWRXD_ALLOW_CLOUD' = 'features.agenticBridge'
}

$entries = foreach ($n in ($names | Sort-Object)) {
    $class = 'production'
    if ($n -match 'DEPRECATED|LEGACY|_OLD') { $class = 'deprecated' }
    elseif ($n -match 'DEBUG|LOG|TRACE|PROFILE|TIMING|STATS|DIAG') { $class = 'diagnostic' }
    elseif ($n -match 'EXPERIMENTAL|BETA|UNSTABLE|NEW_') { $class = 'experimental' }
    [pscustomobject][ordered]@{
        name = $n
        classification = $class
        config_key = if ($knownConfigMap.ContainsKey($n)) { $knownConfigMap[$n] } else { $null }
        source = 'src/include/tools/tests'
    }
}

$inventory = [ordered]@{
    version = '1.0.0'
    generated_at = (Get-Date).ToString('o')
    total = $entries.Count
    production = ($entries | Where-Object { $_.classification -eq 'production' }).Count
    diagnostic = ($entries | Where-Object { $_.classification -eq 'diagnostic' }).Count
    experimental = ($entries | Where-Object { $_.classification -eq 'experimental' }).Count
    deprecated = ($entries | Where-Object { $_.classification -eq 'deprecated' }).Count
    variables = $entries
}
$dir = Split-Path $InventoryPath -Parent
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
$inventory | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $InventoryPath -Encoding UTF8

$lines = @(
    '# RawrXD environment variables',
    '',
    "Generated by `scripts/gen_env_inventory.ps1` on $($inventory.generated_at).",
    '',
    "| Class | Count |",
    "|-------|-------|",
    "| production | $($inventory.production) |",
    "| diagnostic | $($inventory.diagnostic) |",
    "| experimental | $($inventory.experimental) |",
    "| deprecated | $($inventory.deprecated) |",
    "| **total** | **$($inventory.total)** |",
    '',
    'Only variables with a `config_key` are mapped into `rawrxd.config.json`; the rest are runtime-only switches.',
    '',
    '| Variable | Class | Config key |',
    '|----------|-------|------------|'
)
foreach ($e in $entries) {
    $keyText = '-'
    if ($e.config_key) { $keyText = '`' + $e.config_key + '`' }
    $lines += "| ``$($e.name)`` | $($e.classification) | $keyText |"
}
$docDir = Split-Path $DocPath -Parent
if (-not (Test-Path $docDir)) { New-Item -ItemType Directory -Path $docDir -Force | Out-Null }
$lines | Set-Content -LiteralPath $DocPath -Encoding UTF8

Write-Host "Inventory: $($inventory.total) variables -> $InventoryPath"
Write-Host "Doc: $DocPath"