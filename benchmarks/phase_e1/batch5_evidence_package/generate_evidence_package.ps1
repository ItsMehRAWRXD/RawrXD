function Copy-Artifacts {
    param(
        [string]$Source,
        [string]$Dest,
        [string]$Description
    )
    
    if (Test-Path $Source) {
        Copy-Item -Path $Source -Destination $Dest -Recurse -Force
        Write-Host "  ✓ Copied: $Description" -ForegroundColor Green
    } else {
        Write-Host "  ⚠ Missing: $Description" -ForegroundColor Yellow
    }
}

