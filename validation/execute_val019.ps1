# execute_val019.ps1
# Complete VAL-019 execution pipeline
# Generates synthetic vectors, executes stages, produces evidence

param(
    [string]$Mode = "synthetic",  # "synthetic" or "gguf"
    [string]$GGUFPath = "",
    [string]$OutputDir = "val-019/evidence"
)

$ErrorActionPreference = "Stop"

Write-Host "========================================" -ForegroundColor Cyan
Write-Host "  VAL-019 Execution Pipeline" -ForegroundColor Cyan
Write-Host "  Mode: $Mode" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan
Write-Host ""

# Create output directory
New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null

# Step 1: Generate golden vectors
Write-Host "[STEP 1] Generating golden vectors..." -ForegroundColor Yellow

if ($Mode -eq "gguf" -and $GGUFPath -and (Test-Path $GGUFPath)) {
    Write-Host "  Using GGUF model: $GGUFPath"
    python generate_golden_from_gguf.py --model $GGUFPath --output val-019/vectors
} else {
    Write-Host "  Using synthetic vectors (seeded)"
    python generate_embedding_golden.py
    # RMSNorm vectors already generated by generate_golden_vectors.py
}

# Step 2: Execute embedding stage
Write-Host "`n[STEP 2] Executing embedding stage..." -ForegroundColor Yellow

$embeddingResult = @{
    stage = "embedding"
    status = "UNKNOWN"
    input_checksum = ""
    output_checksum = ""
    max_error = 0.0
    runtime_ms = 0.0
    error_msg = ""
}

try {
    $startTime = Get-Date
    
    # Check if executable exists, if not, we can't run it
    if (Test-Path "embedding_stage.exe") {
        $output = & .\embedding_stage.exe val-019/vectors/embedding_input.bin val-019/vectors/embedding_expected.bin $OutputDir/embedding_actual.bin 2>&1
        $exitCode = $LASTEXITCODE
        
        $embeddingResult.runtime_ms = ((Get-Date) - $startTime).TotalMilliseconds
        
        if ($exitCode -eq 0) {
            $embeddingResult.status = "PASS"
        } else {
            $embeddingResult.status = "FAIL"
            $embeddingResult.error_msg = "Exit code: $exitCode"
        }
        
        # Parse output for checksums
        foreach ($line in $output) {
            if ($line -match "Input checksum:\s+(.+)") {
                $embeddingResult.input_checksum = $Matches[1].Trim()
            }
            if ($line -match "Output checksum:\s+(.+)") {
                $embeddingResult.output_checksum = $Matches[1].Trim()
            }
            if ($line -match "Max error:\s+([\d.e+-]+)") {
                $embeddingResult.max_error = [double]$Matches[1]
            }
        }
        
        Write-Host "  Status: $($embeddingResult.status)" -ForegroundColor $(if($embeddingResult.status -eq "PASS"){"Green"}else{"Red"})
        Write-Host "  Runtime: $($embeddingResult.runtime_ms.ToString("F2")) ms"
        Write-Host "  Max Error: $($embeddingResult.max_error)"
    } else {
        $embeddingResult.status = "SKIP"
        $embeddingResult.error_msg = "embedding_stage.exe not found (needs compilation)"
        Write-Host "  Status: SKIP - executable not found" -ForegroundColor Yellow
    }
} catch {
    $embeddingResult.status = "ERROR"
    $embeddingResult.error_msg = $_.Exception.Message
    Write-Host "  Status: ERROR - $($embeddingResult.error_msg)" -ForegroundColor Red
}

# Step 3: Execute RMSNorm stage
Write-Host "`n[STEP 3] Executing RMSNorm stage..." -ForegroundColor Yellow

$rmsnormResult = @{
    stage = "rmsnorm"
    status = "UNKNOWN"
    input_checksum = ""
    output_checksum = ""
    max_error = 0.0
    runtime_ms = 0.0
    mean_rms = 0.0
    min_rms = 0.0
    max_rms = 0.0
    invariants = @{
        has_nan = $false
        has_inf = $false
        output_shape_matches = $true
        rms_range_valid = $true
    }
    error_msg = ""
}

try {
    $startTime = Get-Date
    
    if (Test-Path "rmsnorm_stage.exe") {
        $output = & .\rmsnorm_stage.exe val-019/vectors/rmsnorm_input.bin val-019/vectors/rmsnorm_expected.bin $OutputDir/rmsnorm_actual.bin 2>&1
        $exitCode = $LASTEXITCODE
        
        $rmsnormResult.runtime_ms = ((Get-Date) - $startTime).TotalMilliseconds
        
        if ($exitCode -eq 0) {
            $rmsnormResult.status = "PASS"
        } else {
            $rmsnormResult.status = "FAIL"
            $rmsnormResult.error_msg = "Exit code: $exitCode"
        }
        
        # Parse output
        foreach ($line in $output) {
            if ($line -match "Input checksum:\s+(.+)") {
                $rmsnormResult.input_checksum = $Matches[1].Trim()
            }
            if ($line -match "Output checksum:\s+(.+)") {
                $rmsnormResult.output_checksum = $Matches[1].Trim()
            }
            if ($line -match "Max error:\s+([\d.e+-]+)") {
                $rmsnormResult.max_error = [double]$Matches[1]
            }
            if ($line -match "RMS stats:\s+mean=([\d.]+),\s+min=([\d.]+),\s+max=([\d.]+)") {
                $rmsnormResult.mean_rms = [double]$Matches[1]
                $rmsnormResult.min_rms = [double]$Matches[2]
                $rmsnormResult.max_rms = [double]$Matches[3]
            }
        }
        
        Write-Host "  Status: $($rmsnormResult.status)" -ForegroundColor $(if($rmsnormResult.status -eq "PASS"){"Green"}else{"Red"})
        Write-Host "  Runtime: $($rmsnormResult.runtime_ms.ToString("F2")) ms"
        Write-Host "  Max Error: $($rmsnormResult.max_error)"
        Write-Host "  RMS Stats: mean=$($rmsnormResult.mean_rms), min=$($rmsnormResult.min_rms), max=$($rmsnormResult.max_rms)"
    } else {
        $rmsnormResult.status = "SKIP"
        $rmsnormResult.error_msg = "rmsnorm_stage.exe not found (needs compilation)"
        Write-Host "  Status: SKIP - executable not found" -ForegroundColor Yellow
    }
} catch {
    $rmsnormResult.status = "ERROR"
    $rmsnormResult.error_msg = $_.Exception.Message
    Write-Host "  Status: ERROR - $($rmsnormResult.error_msg)" -ForegroundColor Red
}

# Step 4: Generate unified evidence report
Write-Host "`n[STEP 4] Generating evidence report..." -ForegroundColor Yellow

$evidence = @{
    version = "VAL-019"
    run_id = "VAL-019-run-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
    timestamp = (Get-Date -Format "o")
    commit = "8473df6ea611e082ace66b9876fb17bccebf259d"
    mode = $Mode
    hardware = @{
        cpu = "AMD Ryzen 7 7800X3D"
        gpu = "AMD Radeon RX 7800 XT"
    }
    summary = @{
        total = 2
        passed = 0
        failed = 0
        skipped = 0
        execution_percent = 0.0
    }
    stages = @($embeddingResult, $rmsnormResult)
}

# Calculate summary
foreach ($stage in $evidence.stages) {
    switch ($stage.status) {
        "PASS" { $evidence.summary.passed++ }
        "FAIL" { $evidence.summary.failed++ }
        "SKIP" { $evidence.summary.skipped++ }
    }
}
$evidence.summary.execution_percent = [math]::Round(100.0 * $evidence.summary.passed / $evidence.summary.total, 1)

$reportPath = "$OutputDir/val019_evidence.json"
$evidence | ConvertTo-Json -Depth 10 | Out-File $reportPath

Write-Host "  Report: $reportPath" -ForegroundColor Cyan

# Step 5: Summary
Write-Host "`n========================================" -ForegroundColor Cyan
Write-Host "  Execution Complete" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan
Write-Host "  Total:   $($evidence.summary.total)"
Write-Host "  Passed:  $($evidence.summary.passed)" -ForegroundColor Green
Write-Host "  Failed:  $($evidence.summary.failed)" -ForegroundColor $(if($evidence.summary.failed -gt 0){"Red"}else{"Green"})
Write-Host "  Skipped: $($evidence.summary.skipped)" -ForegroundColor Yellow
Write-Host "  Execution Path: $($evidence.summary.execution_percent)%" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan

# Return exit code
exit $(if ($evidence.summary.failed -gt 0) { 1 } else { 0 })
