# ============================================================================
# Helper Functions
# ============================================================================

function Get-StatusEmoji($passed) {
    if ($passed) { return "✅" }
    return "❌"
}

function Get-StatusColor($passed) {
    if ($passed) { return "Green" }
    return "Red"
}

function Format-Duration($milliseconds) {
    if ($milliseconds -lt 1000) {
        return "$([math]::Round($milliseconds, 0))ms"
    } elseif ($milliseconds -lt 60000) {
        return "$([math]::Round($milliseconds / 1000, 1))s"
    } else {
        $minutes = [math]::Floor($milliseconds / 60000)
        $seconds = [math]::Round(($milliseconds % 60000) / 1000, 0)
        return "$minutes`m $seconds`s"
    }
}

function Get-PerformanceGrade($tps, $latency, $ttft) {
    $score = 0
    
    # TPS scoring
    if ($tps -ge 150) { $score += 40 }
    elseif ($tps -ge 100) { $score += 30 }
    elseif ($tps -ge 50) { $score += 20 }
    else { $score += 10 }
    
    # Latency scoring (lower is better)
    if ($latency -le 2000) { $score += 30 }
    elseif ($latency -le 5000) { $score += 20 }
    elseif ($latency -le 10000) { $score += 10 }
    else { $score += 5 }
    
    # TTFT scoring (lower is better)
    if ($ttft -le 100) { $score += 30 }
    elseif ($ttft -le 250) { $score += 20 }
    elseif ($ttft -le 500) { $score += 10 }
    else { $score += 5 }
    
    if ($score -ge 90) { return "A (Excellent)" }
    if ($score -ge 75) { return "B (Good)" }
    if ($score -ge 60) { return "C (Acceptable)" }
    if ($score -ge 40) { return "D (Below Target)" }
    return "F (Critical)"
}

function Export-ExecutiveReport($data, $outputPath) {
    $report = $ExecutiveTemplate
    
    # Replace placeholders
    $report = $report.Replace("{{VALIDATION_DATE}}", $data.timestamp)
    $report = $report.Replace("{{GENERATION_DATE}}", (Get-Date -Format "yyyy-MM-dd HH:mm:ss"))
    $report = $report.Replace("{{OVERALL_STATUS}}", $(if ($data.certification.all_passed) { "✅ PRODUCTION READY" } else { "❌ NOT CERTIFIED" }))
    
    # Key findings
    $findings = @()
    if ($data.certification.all_passed) {
        $findings += "✅ All certification criteria met"
    } else {
        $findings += "❌ Some certification criteria not met"
    }
    
    if ($data.hardware.multi_gpu_ready) {
        $findings += "✅ Multi-GPU configuration validated"
    } else {
        $findings += "⚠️ Multi-GPU configuration not detected"
    }
    
    if ($data.inference.success_rate -ge 0.95) {
        $findings += "✅ High reliability ($([math]::Round($data.inference.success_rate * 100, 1))% success rate)"
    } else {
        $findings += "⚠️ Reliability below target ($([math]::Round($data.inference.success_rate * 100, 1))% success rate)"
    }
    
    $report = $report.Replace("{{KEY_FINDINGS}}", ($findings | ForEach-Object { "- $_" }) -join "`n")
    
    # Performance table
    $perfTable = @()
    $perfTable += "| Boot Time | < 5000ms | $(Format-Duration $data.boot_time_ms) | $(Get-StatusEmoji $data.certification.boot_passed) |"
    $perfTable += "| TPS | ≥ 100 | $([math]::Round($data.inference.avg_tps, 1)) | $(Get-StatusEmoji $data.certification.tps_passed) |"
    $perfTable += "| Latency | < 5000ms | $(Format-Duration $data.inference.avg_latency_ms) | $(Get-StatusEmoji $data.certification.latency_passed) |"
    $perfTable += "| TTFT | < 250ms | $(Format-Duration $data.inference.avg_ttft_ms) | $(Get-StatusEmoji $data.certification.ttft_passed) |"
    $report = $report.Replace("{{PERFORMANCE_TABLE}}", ($perfTable -join "`n"))
    
    # Hardware summary
    $hwSummary = @()
    if ($data.hardware.r9700_detected) {
        $hwSummary += "- ✅ Radeon AI PRO R9700 32GB detected"
    } else {
        $hwSummary += "- ❌ Radeon AI PRO R9700 not detected"
    }
    
    if ($data.hardware.rx7800xt_detected) {
        $hwSummary += "- ✅ RX 7800 XT 16GB detected"
    } else {
        $hwSummary += "- ❌ RX 7800 XT not detected"
    }
    
    $hwSummary += "- Total GPUs: $($data.hardware.gpu_count)"
    $report = $report.Replace("{{HARDWARE_SUMMARY}}", ($hwSummary -join "`n"))
    
    # Certification status
    $certStatus = @()
    $certStatus += "- Boot Time: $(Get-StatusEmoji $data.certification.boot_passed)"
    $certStatus += "- TPS: $(Get-StatusEmoji $data.certification.tps_passed)"
    $certStatus += "- Latency: $(Get-StatusEmoji $data.certification.latency_passed)"
    $certStatus += "- TTFT: $(Get-StatusEmoji $data.certification.ttft_passed)"
    $certStatus += "- Multi-GPU: $(Get-StatusEmoji $data.certification.multi_gpu_passed)"
    $report = $report.Replace("{{CERTIFICATION_STATUS}}", ($certStatus -join "`n"))
    
    # Recommendations
    $recommendations = @()
    if (-not $data.certification.all_passed) {
        $recommendations += "Address certification failures before production deployment"
    }
    if ($data.inference.avg_tps -lt 100) {
        $recommendations += "Investigate TPS optimization opportunities"
    }
    if ($data.inference.avg_latency_ms -gt 5000) {
        $recommendations += "Review latency optimization strategies"
    }
    if ($recommendations.Count -eq 0) {
        $recommendations += "System is production-ready. Monitor performance continuously."
    }
    $report = $report.Replace("{{RECOMMENDATIONS}}", ($recommendations | ForEach-Object { "1. $_" }) -join "`n")
    
    $report | Out-File $outputPath
    Write-Host "Executive report generated: $outputPath" -ForegroundColor Green
}

function Export-TechnicalReport($data, $outputPath) {
    $report = $TechnicalTemplate
    
    # Replace placeholders
    $report = $report.Replace("{{VALIDATION_DATE}}", $data.timestamp)
    $report = $report.Replace("{{GENERATION_DATE}}", (Get-Date -Format "yyyy-MM-dd HH:mm:ss"))
    $report = $report.Replace("{{FRAMEWORK_VERSION}}", "1.0.0")
    
    # System configuration
    $sysConfig = @()
    $sysConfig += "- **Validation Framework:** v1.0.0"
    $sysConfig += "- **Target URL:** $($data.target_url)"
    $sysConfig += "- **Benchmark Runs:** $($data.benchmark_runs)"
    $sysConfig += "- **Validation Duration:** $(Format-Duration $data.validation_duration_ms)"
    $report = $report.Replace("{{SYSTEM_CONFIG}}", ($sysConfig -join "`n"))
    
    # Inference metrics
    $metrics = @()
    $metrics += "| Average TPS | $([math]::Round($data.inference.avg_tps, 2)) | tokens/s | ≥ 100 | $(Get-StatusEmoji $data.certification.tps_passed) |"
    $metrics += "| Average Latency | $([math]::Round($data.inference.avg_latency_ms, 2)) | ms | < 5000 | $(Get-StatusEmoji $data.certification.latency_passed) |"
    $metrics += "| Average TTFT | $([math]::Round($data.inference.avg_ttft_ms, 2)) | ms | < 250 | $(Get-StatusEmoji $data.certification.ttft_passed) |"
    $metrics += "| Success Rate | $([math]::Round($data.inference.success_rate * 100, 2)) | % | ≥ 95 | $(Get-StatusEmoji ($data.inference.success_rate -ge 0.95)) |"
    $metrics += "| Min TPS | $([math]::Round($data.inference.min_tps, 2)) | tokens/s | - | - |"
    $metrics += "| Max TPS | $([math]::Round($data.inference.max_tps, 2)) | tokens/s | - | - |"
    $report = $report.Replace("{{INFERENCE_METRICS}}", ($metrics -join "`n"))
    
    # Latency analysis
    $latencyAnalysis = @()
    $latencyAnalysis += "- **P50 Latency:** $(Format-Duration $data.inference.p50_latency_ms)"
    $latencyAnalysis += "- **P95 Latency:** $(Format-Duration $data.inference.p95_latency_ms)"
    $latencyAnalysis += "- **P99 Latency:** $(Format-Duration $data.inference.p99_latency_ms)"
    $latencyAnalysis += "- **Latency Variance:** $([math]::Round($data.inference.latency_std_ms, 2))ms (σ)"
    $report = $report.Replace("{{LATENCY_ANALYSIS}}", ($latencyAnalysis -join "`n"))
    
    # Throughput analysis
    $throughputAnalysis = @()
    $grade = Get-PerformanceGrade $data.inference.avg_tps $data.inference.avg_latency_ms $data.inference.avg_ttft_ms
    $throughputAnalysis += "- **Performance Grade:** $grade"
    $throughputAnalysis += "- **Sustained Throughput:** $([math]::Round($data.inference.avg_tps, 2)) tokens/second"
    $throughputAnalysis += "- **Peak Throughput:** $([math]::Round($data.inference.max_tps, 2)) tokens/second"
    $throughputAnalysis += "- **Throughput Stability:** $([math]::Round((1 - ($data.inference.latency_std_ms / $data.inference.avg_latency_ms)) * 100, 1))%"
    $report = $report.Replace("{{THROUGHPUT_ANALYSIS}}", ($throughputAnalysis -join "`n"))
    
    # Hardware details
    $hwDetails = @()
    $hwDetails += "### GPU Configuration"
    $hwDetails += ""
    $hwDetails += "| GPU | Detected | VRAM | Utilization | Temperature |"
    $hwDetails += "|-----|----------|------|-------------|-------------|"
    $hwDetails += "| Radeon AI PRO R9700 | $(Get-StatusEmoji $data.hardware.r9700_detected) | 32GB | $($data.hardware.r9700_utilization)% | $($data.hardware.r9700_temp)°C |"
    $hwDetails += "| RX 7800 XT | $(Get-StatusEmoji $data.hardware.rx7800xt_detected) | 16GB | $($data.hardware.rx7800xt_utilization)% | $($data.hardware.rx7800xt_temp)°C |"
    $hwDetails += ""
    $hwDetails += "### Multi-GPU Status"
    $hwDetails += "- Load Balancing: $(if ($data.hardware.multi_gpu_ready) { "Active" } else { "Inactive" })"
    $hwDetails += "- GPU Count: $($data.hardware.gpu_count)"
    $report = $report.Replace("{{HARDWARE_DETAILS}}", ($hwDetails -join "`n"))
    
    # Error analysis
    $errorAnalysis = @()
    if ($data.inference.errors -and $data.inference.errors.Count -gt 0) {
        $errorAnalysis += "### Error Summary"
        $errorAnalysis += ""
        $errorAnalysis += "| Error Type | Count | Percentage |"
        $errorAnalysis += "|------------|-------|------------|"
        
        $errorGroups = $data.inference.errors | Group-Object error_type
        foreach ($group in $errorGroups) {
            $pct = [math]::Round(($group.Count / $data.benchmark_runs) * 100, 2)
            $errorAnalysis += "| $($group.Name) | $($group.Count) | $pct% |"
        }
    } else {
        $errorAnalysis += "✅ No errors detected during validation"
    }
    $report = $report.Replace("{{ERROR_ANALYSIS}}", ($errorAnalysis -join "`n"))
    
    # Bottleneck analysis
    $bottlenecks = @()
    if ($data.inference.avg_tps -lt 100) {
        $bottlenecks += "- **Throughput Bottleneck:** TPS below target (100 tokens/s)"
    }
    if ($data.inference.avg_latency_ms -gt 5000) {
        $bottlenecks += "- **Latency Bottleneck:** Average latency exceeds 5000ms threshold"
    }
    if ($data.inference.avg_ttft_ms -gt 250) {
        $bottlenecks += "- **TTFT Bottleneck:** Time-to-first-token exceeds 250ms threshold"
    }
    if ($data.hardware.r9700_temp -gt 80) {
        $bottlenecks += "- **Thermal Bottleneck:** R9700 temperature above 80°C"
    }
    if ($bottlenecks.Count -eq 0) {
        $bottlenecks += "✅ No significant bottlenecks detected"
    }
    $report = $report.Replace("{{BOTTLENECK_ANALYSIS}}", ($bottlenecks -join "`n"))
    
    # Optimization recommendations
    $optimizations = @()
    if ($data.inference.avg_tps -lt 100) {
        $optimizations += "Consider batch size optimization to improve throughput"
    }
    if ($data.inference.avg_latency_ms -gt 5000) {
        $optimizations += "Review model quantization settings for latency reduction"
    }
    if ($data.inference.avg_ttft_ms -gt 250) {
        $optimizations += "Investigate prompt caching to reduce TTFT"
    }
    if ($data.hardware.r9700_temp -gt 80) {
        $optimizations += "Monitor GPU cooling and consider thermal management improvements"
    }
    if ($optimizations.Count -eq 0) {
        $optimizations += "System operating within optimal parameters"
    }
    $report = $report.Replace("{{OPTIMIZATION_RECOMMENDATIONS}}", ($optimizations | ForEach-Object { "1. $_" }) -join "`n")
    
    # Raw data summary
    $rawData = @()
    $rawData += "Validation artifacts available in: $ValidationOutputPath"
    $rawData += ""
    $rawData += "### Artifact Files"
    $rawData += "- `boot.log` - Boot sequence timing"
    $rawData += "- `gateway.log` - API validation results"
    $rawData += "- `inference_trace.json` - Request-level metrics"
    $rawData += "- `gpu_metrics.json` - GPU utilization data"
    $rawData += "- `hardware_report.json` - GPU detection results"
    $rawData += "- `benchmark_results.json` - Performance benchmarks"
    $rawData += "- `telemetry_report.json` - Real-time telemetry"
    $rawData += "- `validation_summary.json` - High-level results"
    $rawData += "- `final_validation_report.json` - Certification decision"
    $report = $report.Replace("{{RAW_DATA_SUMMARY}}", ($rawData -join "`n"))
    
    $report | Out-File $outputPath
    Write-Host "Technical report generated: $outputPath" -ForegroundColor Green
}

function Export-CIReport($data, $outputPath) {
    # CI-friendly JSON report
    $ciReport = @{
        schema_version = "1.0"
        timestamp = (Get-Date -Format "yyyy-MM-ddTHH:mm:ssZ")
        
        summary = @{
            status = $(if ($data.certification.all_passed) { "PASS" } else { "FAIL" })
            certification_passed = $data.certification.all_passed
            metrics_passed = ($data.certification.psobject.properties | Where-Object { $_.Value -eq $true }).Count
            metrics_total = ($data.certification.psobject.properties | Where-Object { $_.Name -ne "all_passed" }).Count
        }
        
        performance = @{
            tps = @{
                value = $data.inference.avg_tps
                target = 100
                passed = $data.certification.tps_passed
            }
            latency_ms = @{
                value = $data.inference.avg_latency_ms
                target = 5000
                passed = $data.certification.latency_passed
            }
            ttft_ms = @{
                value = $data.inference.avg_ttft_ms
                target = 250
                passed = $data.certification.ttft_passed
            }
            boot_ms = @{
                value = $data.boot_time_ms
                target = 5000
                passed = $data.certification.boot_passed
            }
        }
        
        hardware = @{
            multi_gpu_ready = $data.hardware.multi_gpu_ready
            gpu_count = $data.hardware.gpu_count
            r9700_detected = $data.hardware.r9700_detected
            rx7800xt_detected = $data.hardware.rx7800xt_detected
        }
        
        artifacts = @{
            location = $ValidationOutputPath
            files = @(
                "boot.log",
                "gateway.log",
                "inference_trace.json",
                "gpu_metrics.json",
                "hardware_report.json",
                "benchmark_results.json",
                "telemetry_report.json",
                "validation_summary.json",
                "final_validation_report.json"
            )
        }
    }
    
    $ciReport | ConvertTo-Json -Depth 5 | Out-File $outputPath
    Write-Host "CI report generated: $outputPath" -ForegroundColor Green
}

# ============================================================================
# Main Execution
# ============================================================================

Write-Host "RawrXD Validation Report Generator" -ForegroundColor Cyan
Write-Host "==================================" -ForegroundColor Cyan
Write-Host ""

# Load validation data
$validationReportPath = Join-Path $ValidationOutputPath "final_validation_report.json"

if (-not (Test-Path $validationReportPath)) {
    throw "Validation report not found: $validationReportPath"
}

Write-Host "Loading validation data from: $validationReportPath" -ForegroundColor Gray
$data = Get-Content $validationReportPath | ConvertFrom-Json
Write-Host "Validation data loaded successfully" -ForegroundColor Green
Write-Host ""

# Create output directory if needed
if (-not (Test-Path $OutputDirectory)) {
    New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
}

$timestamp = Get-Date -Format "yyyyMMdd_HHmmss"
$reportsGenerated = @()

# Generate requested reports
switch ($ReportType) {
    "Executive" {
        $execPath = Join-Path $OutputDirectory "validation_report_executive_$timestamp.md"
        Export-ExecutiveReport $data $execPath
        $reportsGenerated += $execPath
    }
    
    "Technical" {
        $techPath = Join-Path $OutputDirectory "validation_report_technical_$timestamp.md"
        Export-TechnicalReport $data $techPath
        $reportsGenerated += $techPath
    }
    
    "Full" {
        $execPath = Join-Path $OutputDirectory "validation_report_executive_$timestamp.md"
        Export-ExecutiveReport $data $execPath
        $reportsGenerated += $execPath
        
        $techPath = Join-Path $OutputDirectory "validation_report_technical_$timestamp.md"
        Export-TechnicalReport $data $techPath
        $reportsGenerated += $techPath
        
        $ciPath = Join-Path $OutputDirectory "validation_report_ci_$timestamp.json"
        Export-CIReport $data $ciPath
        $reportsGenerated += $ciPath
    }
    
    "CI" {
        $ciPath = Join-Path $OutputDirectory "validation_report_ci_$timestamp.json"
        Export-CIReport $data $ciPath
        $reportsGenerated += $ciPath
    }
}

# Include artifacts if requested
if ($IncludeArtifacts) {
    $artifactsDir = Join-Path $OutputDirectory "artifacts_$timestamp"
    New-Item -ItemType Directory -Path $artifactsDir -Force | Out-Null
    
    Copy-Item -Path "$ValidationOutputPath\*" -Destination $artifactsDir -Recurse
    Write-Host "Artifacts copied to: $artifactsDir" -ForegroundColor Green
}

# Summary
Write-Host ""
Write-Host "Report Generation Complete" -ForegroundColor Cyan
Write-Host "==========================" -ForegroundColor Cyan
Write-Host "Reports generated:"
foreach ($report in $reportsGenerated) {
    Write-Host "  - $report" -ForegroundColor Gray
}

if ($OpenReport -and $reportsGenerated.Count -gt 0) {
    $firstReport = $reportsGenerated[0]
    Write-Host ""
    Write-Host "Opening report: $firstReport" -ForegroundColor Green
    Start-Process $firstReport
}

Write-Host ""
Write-Host "Done!" -ForegroundColor Green
