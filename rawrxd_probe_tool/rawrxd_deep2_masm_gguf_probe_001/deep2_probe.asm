; ---------------- main ----------------
start PROC
    sub rsp,72
    mov gguf_alignment,DEFAULT_GGUF_ALIGNMENT
    mov sys_use_mask,SYS_USE_FILE_IO or SYS_USE_FILE_MAPPING or SYS_USE_OUTPUT_FILES or SYS_USE_STATIC_ARENAS

    call parse_model_arg
    test eax,eax
    jnz @@open
    lea rcx,msg_usage
    call stdout_z
    mov ecx,2
    call ExitProcess

@@open:
    lea rcx,path_buf
    mov rdx,GENERIC_READ
    mov r8d,FILE_SHARE_READ
    xor r9d,r9d
    mov qword ptr [rsp+32],OPEN_EXISTING
    mov qword ptr [rsp+40],FILE_ATTRIBUTE_NORMAL
    mov qword ptr [rsp+48],0
    call CreateFileW
    cmp rax,INVALID_HANDLE_VALUE
    jne @F
    lea rcx,msg_open_fail
    call stdout_z
    mov ecx,3
    call ExitProcess
@@:
    mov file_handle,rax

    mov rcx,TRACE_KIND_OBSERVE
    mov edx,OP_FILE_OPEN
    xor r8,r8
    xor r9,r9
    mov qword ptr [rsp+32],0
    mov dword ptr [rsp+40],0
    mov dword ptr [rsp+48],CLASS_HARD
    mov qword ptr [rsp+56],0
    call trace_emit

    mov rcx,file_handle
    lea rdx,file_size
    call GetFileSizeEx
    test eax,eax
    jz @@bad

    mov rcx,file_handle
    xor rdx,rdx
    mov r8d,PAGE_READONLY
    xor r9d,r9d
    mov qword ptr [rsp+32],0
    mov qword ptr [rsp+40],0
    call CreateFileMappingW
    test rax,rax
    jnz @F
    lea rcx,msg_map_fail
    call stdout_z
    mov ecx,4
    call ExitProcess
@@:
    mov map_handle,rax
    mov rcx,map_handle
    mov edx,FILE_MAP_READ
    xor r8d,r8d
    xor r9d,r9d
    mov qword ptr [rsp+32],0
    call MapViewOfFile
    test rax,rax
    jnz @F
    lea rcx,msg_map_fail
    call stdout_z
    mov ecx,5
    call ExitProcess
@@:
    mov map_base,rax
    mov cursor,rax
    mov rdx,file_size
    add rdx,rax
    mov map_end,rdx

    ; GGUF header
    call read_u32
    cmp eax,GGUF_MAGIC
    jne @@bad
    call read_u32
    cmp rax,-1
    je @@bad
    mov gguf_version,eax
    cmp eax,2
    jb @@bad
    cmp eax,3
    ja @@bad
    call read_u64
    cmp rax,-1
    je @@bad
    mov tensor_count,rax
    call read_u64
    cmp rax,-1
    je @@bad
    mov metadata_count,rax
    cmp rax,MAX_METADATA
    ja @@bad

    mov rcx,TRACE_KIND_VERIFY
    mov edx,OP_GGUF_HEADER
    xor r8,r8
    mov r9,tensor_count
    mov rax,metadata_count
    mov qword ptr [rsp+32],rax
    mov dword ptr [rsp+40],0
    mov dword ptr [rsp+48],CLASS_PROVEN
    mov qword ptr [rsp+56],0
    call trace_emit

    call parse_metadata
    test eax,eax
    jz @@bad
    call parse_tensors
    test eax,eax
    jz @@bad

    ; Verification stamp: all tensor absolute offsets are inside mapped file.
    mov rcx,TRACE_KIND_VERIFY
    mov edx,OP_VERIFY_LAYOUT
    xor r8,r8
    mov r9,tensor_data_start
    mov rax,file_size
    mov qword ptr [rsp+32],rax
    mov dword ptr [rsp+40],0
    mov dword ptr [rsp+48],CLASS_PROVEN
    mov qword ptr [rsp+56],0
    call trace_emit

    call emit_model_header
    call emit_tensor_header
    call emit_quant_header
    call emit_system_header
    call emit_stamp_header
    call emit_rxi

    mov rcx,TRACE_KIND_CLASSIFY
    mov edx,OP_COMPLETE
    xor r8,r8
    mov r9,tensor_count
    mov rax,metadata_count
    mov qword ptr [rsp+32],rax
    mov dword ptr [rsp+40],0
    mov dword ptr [rsp+48],CLASS_PROVEN
    mov qword ptr [rsp+56],0
    call trace_emit
    call emit_trace

    lea rcx,msg_ok
    call stdout_z
    lea rcx,msg_outputs
    call stdout_z

    mov rcx,map_base
    call UnmapViewOfFile
    mov rcx,map_handle
    call CloseHandle
    mov rcx,file_handle
    call CloseHandle
    xor ecx,ecx
    call ExitProcess

@@bad:
    lea rcx,msg_bad_gguf
    call stdout_z
    mov ecx,6
    call ExitProcess
start ENDP

