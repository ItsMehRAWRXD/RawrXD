u64_to_dec PROC
    ; rcx=value => rax=ptr ASCIIZ in decbuf
    push rdi
    lea rdi,decbuf+31
    mov byte ptr [rdi],0
    mov rax,rcx
    mov r8,10
    test rax,rax
    jnz @@loop
    dec rdi
    mov byte ptr [rdi],'0'
    mov rax,rdi
    pop rdi
    ret
@@loop:
    xor rdx,rdx
    div r8
    add dl,'0'
    dec rdi
    mov [rdi],dl
    test rax,rax
    jnz @@loop
    mov rax,rdi
    pop rdi
    ret
u64_to_dec ENDP

u64_to_hex PROC
    ; rcx=value => 16 hex digits + h
    push rdi
    lea rdi,hexbuf
    mov rax,rcx
    mov r8d,16
@@loop:
    rol rax,4
    mov dl,al
    and dl,0Fh
    cmp dl,9
    jbe @F
    add dl,7
@@: add dl,'0'
    mov [rdi],dl
    inc rdi
    dec r8d
    jnz @@loop
    mov byte ptr [rdi],'h'
    inc rdi
    mov byte ptr [rdi],0
    lea rax,hexbuf
    pop rdi
    ret
u64_to_hex ENDP

