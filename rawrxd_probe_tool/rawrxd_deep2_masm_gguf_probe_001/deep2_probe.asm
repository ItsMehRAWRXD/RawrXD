; ---------------- command line: copy argv[1] to path_buf ----------------
parse_model_arg PROC
    push rsi
    push rdi
    sub rsp, 40
    call GetCommandLineW
    mov rsi, rax
    lea rdi, path_buf
    ; skip leading spaces
@@s0:
    mov ax, [rsi]
    cmp ax, ' '
    jne @@exe
    add rsi,2
    jmp @@s0
@@exe:
    cmp word ptr [rsi], '"'
    jne @@exe_plain
    add rsi,2
@@qskip:
    mov ax,[rsi]
    test ax,ax
    jz @@fail
    add rsi,2
    cmp ax,'"'
    jne @@qskip
    jmp @@after_exe
@@exe_plain:
@@pskip:
    mov ax,[rsi]
    test ax,ax
    jz @@fail
    cmp ax,' '
    je @@after_exe
    add rsi,2
    jmp @@pskip
@@after_exe:
@@sp:
    mov ax,[rsi]
    cmp ax,' '
    jne @@arg
    add rsi,2
    jmp @@sp
@@arg:
    test ax,ax
    jz @@fail
    cmp ax,'"'
    jne @@copy_plain
    add rsi,2
@@copy_q:
    mov ax,[rsi]
    test ax,ax
    jz @@done
    cmp ax,'"'
    je @@done
