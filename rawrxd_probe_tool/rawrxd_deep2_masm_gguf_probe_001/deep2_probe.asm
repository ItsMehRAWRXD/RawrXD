trace_emit ENDP

; ---------------- skip GGUF metadata value ----------------
; ecx=type. eax=1 success
skip_value PROC
    push rbx
    push rsi
    push rdi
    sub rsp,32
    mov ebx,ecx
    cmp ebx,GGUF_TYPE_UINT8
    je @@b1
    cmp ebx,GGUF_TYPE_INT8
    je @@b1
    cmp ebx,GGUF_TYPE_BOOL
    je @@b1
    cmp ebx,GGUF_TYPE_UINT16
    je @@b2
    cmp ebx,GGUF_TYPE_INT16
    je @@b2
    cmp ebx,GGUF_TYPE_UINT32
    je @@b4
    cmp ebx,GGUF_TYPE_INT32
    je @@b4
    cmp ebx,GGUF_TYPE_FLOAT32
    je @@b4
    cmp ebx,GGUF_TYPE_UINT64
    je @@b8
    cmp ebx,GGUF_TYPE_INT64
    je @@b8
    cmp ebx,GGUF_TYPE_FLOAT64
    je @@b8
    cmp ebx,GGUF_TYPE_STRING
    je @@str
    cmp ebx,GGUF_TYPE_ARRAY
    je @@arr
    xor eax,eax
    jmp @@out
@@b1:
    mov ecx,1
    call need_bytes
    test eax,eax
    jz @@out
    add cursor,1
    mov eax,1
    jmp @@out
@@b2:
    mov ecx,2
    call need_bytes
    test eax,eax
    jz @@out
    add cursor,2
    mov eax,1
    jmp @@out
@@b4:
    mov ecx,4
    call need_bytes
    test eax,eax
    jz @@out
    add cursor,4
    mov eax,1
    jmp @@out
@@b8:
    mov ecx,8
    call need_bytes
    test eax,eax
    jz @@out
    add cursor,8
    mov eax,1
    jmp @@out
@@str:
    call read_gguf_string
    jc @@fail
    mov eax,1
    jmp @@out
@@arr:
    call read_u32
    cmp rax,-1
    je @@fail
    mov ebx,eax                    ; element type
    call read_u64
    cmp rax,-1
    je @@fail
    mov rdi,rax                    ; count
    xor rsi,rsi
@@aloop:
    cmp rsi,rdi
    jae @@aok
    mov ecx,ebx
    call skip_value
    test eax,eax
    jz @@fail
    inc rsi
    jmp @@aloop
@@aok:
    mov eax,1
    jmp @@out
@@fail:
    xor eax,eax
@@out:
    add rsp,32
    pop rdi
    pop rsi
    pop rbx
    ret
skip_value ENDP

; ---------------- parse metadata ----------------
parse_metadata PROC
    push rbx
    push rsi
    push rdi
    sub rsp,64
    xor rbx,rbx
@@loop:
    cmp rbx,metadata_count
    jae @@ok
    call read_gguf_string
    jc @@fail
    mov rsi,rax                    ; key ptr
    mov rdi,rdx                    ; key len
    mov rcx,rsi
    mov rdx,rdi
    call hash64
    mov qword ptr [rsp+32],rax     ; key hash

    mov ecx,TRACE_KIND_OBSERVE
    mov edx,OP_METADATA_KEY
    mov r8,rax
    mov r9,rbx
    mov qword ptr [rsp+32],rdi
    mov dword ptr [rsp+40],0
    mov dword ptr [rsp+48],CLASS_DECLARED
    mov qword ptr [rsp+56],0
    call trace_emit

    call read_u32
    cmp rax,-1
    je @@fail
    mov dword ptr [rsp+36],eax     ; type

    ; general.architecture
    mov rcx,rsi
    mov rdx,rdi
    lea r8,key_arch
    mov r9d,KEY_ARCH_LEN
    call bytes_eq
    test eax,eax
    jz @@check_align
    cmp dword ptr [rsp+36],GGUF_TYPE_STRING
    jne @@generic
    call read_gguf_string
    jc @@fail
    mov rcx,rax
    ; hash architecture string
    call hash64
    mov arch_hash,rax
    ; The RXI retains a stable architecture-string hash rather than a process pointer.
    jmp @@next

@@check_align:
    mov rcx,rsi
    mov rdx,rdi
    lea r8,key_align
    mov r9d,KEY_ALIGN_LEN
    call bytes_eq
    test eax,eax
    jz @@generic
    mov eax,dword ptr [rsp+36]
    cmp eax,GGUF_TYPE_UINT32
    jne @@align64
    call read_u32
    cmp rax,-1
    je @@fail
    mov gguf_alignment,rax
    jmp @@next
@@align64:
    cmp eax,GGUF_TYPE_UINT64
    jne @@generic
    call read_u64
    cmp rax,-1
    je @@fail
    mov gguf_alignment,rax
    jmp @@next

@@generic:
    mov ecx,dword ptr [rsp+36]
    call skip_value
    test eax,eax
    jz @@fail
@@next:
    inc rbx
    jmp @@loop
@@ok:
    mov eax,1
    jmp @@out
@@fail:
    xor eax,eax
@@out:
    add rsp,64
    pop rdi
    pop rsi
    pop rbx
    ret
parse_metadata ENDP

; ---------------- parse tensor infos ----------------
parse_tensors PROC
    push rbx
    push rsi
    push rdi
    sub rsp,64
    mov rax,tensor_count
    cmp rax,MAX_TENSORS
    ja @@fail
    xor rbx,rbx
@@loop:
    cmp rbx,tensor_count
    jae @@finish
    call read_gguf_string
    jc @@fail
    mov rsi,rax
    mov rdi,rdx
    mov rcx,rsi
    call hash64
    mov qword ptr [rsp+32],rax     ; name hash

    mov ecx,4
    call need_bytes
    test eax,eax
    jz @@fail
    call read_u32
    cmp rax,-1
    je @@fail
    mov dword ptr [rsp+40],eax     ; ndims
    cmp eax,32
    ja @@fail

    mov rax,rbx
    imul rax,SIZEOF TENSOR_REC
    lea r10,tensor_records
    add r10,rax
    mov rax,qword ptr [rsp+32]
    mov [r10].TENSOR_REC.NameHash,rax
    mov eax,dword ptr [rsp+40]
    mov [r10].TENSOR_REC.NDims,eax
    mov qword ptr [r10].TENSOR_REC.Dim0,1
    mov qword ptr [r10].TENSOR_REC.Dim1,1
    mov qword ptr [r10].TENSOR_REC.Dim2,1
    mov qword ptr [r10].TENSOR_REC.Dim3,1

    xor r11d,r11d
@@dims:
    cmp r11d,dword ptr [rsp+40]
    jae @@dtype
    call read_u64
    cmp rax,-1
    je @@fail
    cmp r11d,0
    jne @F
    mov [r10].TENSOR_REC.Dim0,rax
@@: cmp r11d,1
    jne @F
    mov [r10].TENSOR_REC.Dim1,rax
@@: cmp r11d,2
    jne @F
    mov [r10].TENSOR_REC.Dim2,rax
@@: cmp r11d,3
    jne @F
    mov [r10].TENSOR_REC.Dim3,rax
@@:
    inc r11d
    jmp @@dims
@@dtype:
    call read_u32
    cmp rax,-1
    je @@fail
    mov [r10].TENSOR_REC.TypeId,eax
    mov r11d,eax
    cmp r11d,64
    jae @@qhi
    mov rax,1
    mov cl,r11b
    shl rax,cl
    or quant_mask_lo,rax
    jmp @@offset
@@qhi:
    cmp r11d,128
    jae @@offset
    sub r11d,64
    mov rax,1
    mov cl,r11b
    shl rax,cl
    or quant_mask_hi,rax
@@offset:
    call read_u64
    cmp rax,-1
    je @@fail
    mov [r10].TENSOR_REC.RelativeOffset,rax

    mov ecx,TRACE_KIND_OBSERVE
    mov edx,OP_TENSOR_INFO
    mov r8,rbx
    mov r9,qword ptr [rsp+32]
    mov qword ptr [rsp+32],rax
    mov dword ptr [rsp+40],0
    mov dword ptr [rsp+48],CLASS_DECLARED
    mov qword ptr [rsp+56],0
    call trace_emit

    inc rbx
    jmp @@loop
@@finish:
    ; tensor data begins at aligned end of tensor table
    mov rax,cursor
    sub rax,map_base
    mov rcx,gguf_alignment
    test rcx,rcx
    jnz @F
    mov rcx,DEFAULT_GGUF_ALIGNMENT
    mov gguf_alignment,rcx
@@:
    dec rcx
    add rax,rcx
    not rcx
    and rax,rcx
    mov tensor_data_start,rax

    ; absolute offsets
    xor rbx,rbx
@@absloop:
    cmp rbx,tensor_count
    jae @@spans
    mov rax,rbx
    imul rax,SIZEOF TENSOR_REC
    lea r10,tensor_records
    add r10,rax
    mov rax,[r10].TENSOR_REC.RelativeOffset
    add rax,tensor_data_start
    mov [r10].TENSOR_REC.AbsoluteOffset,rax
    cmp rax,file_size
    jae @@fail
    inc rbx
    jmp @@absloop

@@spans:
    ; storage span = next greater tensor absolute offset - current, or EOF-current.
    xor rbx,rbx
@@outer:
    cmp rbx,tensor_count
    jae @@ok
    mov rax,rbx
    imul rax,SIZEOF TENSOR_REC
    lea r10,tensor_records
    add r10,rax
    mov rsi,[r10].TENSOR_REC.AbsoluteOffset
    mov rdi,file_size
    xor r11,r11
@@inner:
    cmp r11,tensor_count
    jae @@span_done
    mov rax,r11
    imul rax,SIZEOF TENSOR_REC
    lea rdx,tensor_records
    add rdx,rax
    mov rax,[rdx].TENSOR_REC.AbsoluteOffset
    cmp rax,rsi
    jbe @@inext
    cmp rax,rdi
    jae @@inext
    mov rdi,rax
@@inext:
    inc r11
    jmp @@inner
@@span_done:
    mov rax,rdi
    sub rax,rsi
    mov [r10].TENSOR_REC.StorageSpan,rax
    inc rbx
    jmp @@outer
@@ok:
    mov eax,1
    jmp @@out
@@fail:
    xor eax,eax
@@out:
    add rsp,64
    pop rdi
    pop rsi
    pop rbx
    ret
parse_tensors ENDP

