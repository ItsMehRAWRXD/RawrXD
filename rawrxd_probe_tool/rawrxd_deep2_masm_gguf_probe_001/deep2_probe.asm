emit_tensor_line PROC
    ; rbx=tensor index, rsi=rec, rdi=suffix, rdx=value, r8d=hex?  build symbolic name into linebuf
    push rax
    push rcx
    push r9
    push r10
    lea r9,linebuf
    lea r10,s_tensor_prefix
@@p:
    mov al,[r10]
    test al,al
    jz @@id
    mov [r9],al
    inc r9
    inc r10
    jmp @@p
@@id:
    ; four hex digits of low 16-bit tensor index
    mov eax,ebx
    mov ecx,4
@@hx:
    rol ax,4
    mov r10b,al
    and r10b,0Fh
    cmp r10b,9
    jbe @F
    add r10b,7
@@: add r10b,'0'
    mov [r9],r10b
    inc r9
    dec ecx
    jnz @@hx
    mov r10,rdi
@@suf:
    mov al,[r10]
    test al,al
    jz @@done
    mov [r9],al
    inc r9
    inc r10
    jmp @@suf
@@done:
    mov byte ptr [r9],0
    lea rcx,linebuf
    test r8d,r8d
    jz @@dec
    call emit_equ_hex
    jmp @@ret
@@dec:
    call emit_equ_dec
@@ret:
    pop r10
    pop r9
    pop rcx
    pop rax
    ret
emit_tensor_line ENDP

