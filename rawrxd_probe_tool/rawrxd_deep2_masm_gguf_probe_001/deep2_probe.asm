; ---------------- bounds-safe readers ----------------
need_bytes PROC
    ; rcx=count; eax=1 if cursor+count <= end
    mov rax,cursor
    mov rdx,rax
    add rdx,rcx
    jc @@bad
    cmp rdx,map_end
    ja @@bad
    mov eax,1
    ret
@@bad:
    xor eax,eax
    ret
need_bytes ENDP

read_u32 PROC
    mov ecx,4
    call need_bytes
    test eax,eax
    jz @@bad
    mov rdx,cursor
    mov eax,dword ptr [rdx]
    add rdx,4
    mov cursor,rdx
    ret
@@bad:
    mov rax,-1
    ret
read_u32 ENDP

read_u64 PROC
    mov ecx,8
    call need_bytes
    test eax,eax
    jz @@bad
    mov rdx,cursor
    mov rax,qword ptr [rdx]
    add rdx,8
    mov cursor,rdx
    ret
@@bad:
    mov rax,-1
    ret
read_u64 ENDP

; returns rax=ptr, rdx=len; CF=1 on failure
read_gguf_string PROC
    call read_u64
    cmp rax,-1
    je @@bad
    mov r8,rax
    mov rcx,r8
    call need_bytes
    test eax,eax
    jz @@bad
    mov rax,cursor
    mov rdx,r8
    add cursor,r8
    clc
    ret
@@bad:
    stc
    ret
read_gguf_string ENDP

; FNV-1a64: rcx=ptr rdx=len => rax
hash64 PROC
    mov rax,1469598103934665603
    mov r8,1099511628211
    xor r9,r9
@@h:
    cmp r9,rdx
    jae @@done
    movzx r10d,byte ptr [rcx+r9]
    xor rax,r10
    imul rax,r8
    inc r9
    jmp @@h
@@done:
    ret
hash64 ENDP

; rcx=p1 rdx=len1 r8=p2 r9=len2; eax bool
bytes_eq PROC
    cmp rdx,r9
    jne @@no
    xor r10,r10
@@loop:
    cmp r10,rdx
    jae @@yes
    mov al,[rcx+r10]
    cmp al,[r8+r10]
    jne @@no
    inc r10
    jmp @@loop
@@yes:
    mov eax,1
    ret
@@no:
    xor eax,eax
    ret
bytes_eq ENDP

; ---------------- causal trace; no time ----------------
; rcx=kind edx=op r8=obj r9=A, stack +40=B +48=flags +56=class +64=parent
trace_emit PROC
