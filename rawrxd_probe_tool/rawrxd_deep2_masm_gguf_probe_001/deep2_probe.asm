    mov rax,trace_seq
    mov [r11].TRACE_REC.Seq,rax
    mov rax,qword ptr [rsp+64]
    mov [r11].TRACE_REC.ParentSeq,rax
    mov [r11].TRACE_REC.Kind,ecx
    mov [r11].TRACE_REC.Op,edx
    mov [r11].TRACE_REC.ObjectId,r8
    mov qword ptr [r11].TRACE_REC.InputGen,0
    mov qword ptr [r11].TRACE_REC.OutputGen,0
    mov [r11].TRACE_REC.A,r9
    mov rax,qword ptr [rsp+40]
    mov [r11].TRACE_REC.B,rax
    mov eax,dword ptr [rsp+48]
    mov [r11].TRACE_REC.Flags,eax
    mov eax,dword ptr [rsp+56]
