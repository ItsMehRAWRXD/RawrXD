static inline float iq_f16(uint16_t h) {
    uint32_t sign = (uint32_t)(h & 0x8000u) << 16;
    uint32_t exp  = (h >> 10) & 0x1Fu;
    uint32_t frac =  h        & 0x03FFu;
    if (exp == 0) {
        if (!frac) { float f; uint32_t b = sign; memcpy(&f,&b,4); return f; }
        uint32_t e=1, ff=frac;
        while (!(ff & 0x400u)) { ff<<=1; e++; }
        ff &= 0x3FFu;
        uint32_t b = sign | ((127-15+2-e)<<23) | (ff<<13);
        float f; memcpy(&f,&b,4); return f;
    }
    if (exp == 31) {
        uint32_t b = sign | 0x7F800000u | (frac<<13);
        float f; memcpy(&f,&b,4); return f;
    }
    uint32_t b = sign | ((exp+127-15)<<23) | (frac<<13);
    float f; memcpy(&f,&b,4); return f;
}

