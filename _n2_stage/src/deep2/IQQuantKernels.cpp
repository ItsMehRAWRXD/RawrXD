// IQQuantKernels.cpp
// Scalar GEMV + dequant stubs for IQ2_XXS/XS/S/M, IQ3_XXS/S/M, IQ4_NL/XS.
// Each kernel zeroes the output row and emits one diagnostic per type per
// process lifetime so LinearW does not throw on IQ-quantized tensors.
// Full implementations require the ggml lookup tables (iq2_xxs_grid etc.);
// those tables must be ported from ggml-quants.c before these stubs are
// promoted to production kernels.
//
// Block byte sizes (from ggml-quants.h, QK_K=256 or QK4_NL=32):
//   IQ2_XXS  type=16  18 bytes / 32 values
//   IQ2_XS   type=17  22 bytes / 32 values  (2+2+16+2 layout)
//   IQ2_S    type=18  22 bytes / 32 values
//   IQ2_M    type=19  36 bytes / 32 values
//   IQ3_XXS  type=20  26 bytes / 32 values
//   IQ3_S    type=21  44 bytes / 32 values
//   IQ3_M    type=22  46 bytes / 32 values
//   IQ4_NL   type=23  18 bytes / 32 values
//   IQ4_XS   type=24  22 bytes / 32 values

