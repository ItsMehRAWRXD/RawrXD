#!/usr/bin/env python3
"""
Report generator for RawrXD validation results
Creates formatted reports from JSON validation output
"""

import json
import sys
from pathlib import Path
from datetime import datetime

def generate_markdown_report(data, output_path):
    """Generate a Markdown report from validation data"""
    
    with open(output_path, 'w') as f:
        f.write("# RawrXD Validation Report\n\n")
        f.write(f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
        
        # Summary
        summary = data.get('summary', {})
        f.write("## Summary\n\n")
        f.write(f"- **Total Tests:** {summary.get('total_tests', 0)}\n")
        f.write(f"- **Passed:** {summary.get('passed_tests', 0)} ✓\n")
        f.write(f"- **Failed:** {summary.get('failed_tests', 0)}\n")
        f.write(f"- **Skipped:** {summary.get('skipped_tests', 0)}\n")
        f.write(f"- **Pass Rate:** {summary.get('pass_rate', 0):.1f}%\n")
        f.write(f"- **Total Time:** {summary.get('total_time_ms', 0):.2f}ms\n\n")
        
        # Status
        if summary.get('failed_tests', 0) == 0:
            f.write("**Status:** ✅ ALL TESTS PASSED\n\n")
        else:
            f.write("**Status:** ❌ SOME TESTS FAILED\n\n")
        
        # Suites
        f.write("## Test Suites\n\n")
        suites = data.get('suites', [])
        
        for suite in suites:
            name = suite.get('name', 'Unknown')
            total = suite.get('total', 0)
            passed = suite.get('passed', 0)
            failed = suite.get('failed', 0)
            skipped = suite.get('skipped', 0)
            time = suite.get('total_time_ms', 0)
            
            f.write(f"### {name}\n\n")
            f.write(f"- Tests: {total}\n")
            f.write(f"- Passed: {passed}\n")
            f.write(f"- Failed: {failed}\n")
            f.write(f"- Skipped: {skipped}\n")
            f.write(f"- Time: {time:.2f}ms\n\n")
        
        # Kernel results
        kernels = data.get('kernel_results', [])
        if kernels:
            f.write("## Kernel Results\n\n")
            f.write("| Kernel | Elements | Speedup | Max Error | Status |\n")
            f.write("|--------|----------|---------|-----------|--------|\n")
            
            for k in kernels:
                name = k.get('kernel_name', 'Unknown')
                elems = k.get('num_elements', 0)
                speedup = k.get('speedup', 0)
                error = k.get('max_abs_error', 0)
                passed = "✓" if k.get('passed', False) else "✗"
                
                f.write(f"| {name} | {elems} | {speedup:.2f}x | {error:.6f} | {passed} |\n")
            
            f.write("\n")
        
        f.write("---\n\n")
        f.write("*Generated by RawrXD Validation Harness*\n")

def generate_csv_report(data, output_path):
    """Generate a CSV report from validation data"""
    
    with open(output_path, 'w') as f:
        # Header
        f.write("Suite,Test,Status,Time_ms\n")
        
        # Suites
        suites = data.get('suites', [])
        for suite in suites:
            suite_name = suite.get('name', 'Unknown')
            # In a real implementation, we'd iterate through individual test cases
            # For now, just write suite summary
            total = suite.get('total', 0)
            passed = suite.get('passed', 0)
            failed = suite.get('failed', 0)
            time = suite.get('total_time_ms', 0)
            
            status = "PASSED" if failed == 0 else "FAILED"
            f.write(f"{suite_name},Summary,{status},{time:.2f}\n")

def main():
    if len(sys.argv) < 2:
        print("Usage: generate_report.py <validation.json> [output.md|output.csv]")
        sys.exit(1)
    
    json_path = sys.argv[1]
    output_path = sys.argv[2] if len(sys.argv) > 2 else None
    
    try:
        with open(json_path, 'r') as f:
            data = json.load(f)
    except Exception as e:
        print(f"Error loading JSON: {e}")
        sys.exit(1)
    
    # Determine output format
    if output_path:
        if output_path.endswith('.md'):
            generate_markdown_report(data, output_path)
            print(f"Markdown report generated: {output_path}")
        elif output_path.endswith('.csv'):
            generate_csv_report(data, output_path)
            print(f"CSV report generated: {output_path}")
        else:
            # Default to markdown
            if not output_path.endswith('.md'):
                output_path += '.md'
            generate_markdown_report(data, output_path)
            print(f"Markdown report generated: {output_path}")
    else:
        # Default output
        output_path = json_path.replace('.json', '.md')
        generate_markdown_report(data, output_path)
        print(f"Markdown report generated: {output_path}")

if __name__ == '__main__':
    main()
