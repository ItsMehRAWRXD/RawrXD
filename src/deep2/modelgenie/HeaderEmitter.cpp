//=============================================================================
// TensorROM.generated.hpp
//=============================================================================
bool HeaderEmitter::EmitTensorROM(const ModelGenome& genome) {
    auto out = OpenHeader("TensorROM.generated.hpp", "TENSOR_ROM_GENERATED_HPP");
    if (!out.is_open()) return false;
    
    WritePreamble(out, "TENSOR_ROM_GENERATED_HPP", "Tensor ROM descriptors (no runtime name parsing)");
    
    out << "namespace RawrXD {\n";
    out << "namespace Deep2 {\n";
    out << "namespace Generated {\n\n";
    
    out << "struct TensorROM {\n";
    Indent(out, 1); out << "uint32_t tensorId;\n";
    Indent(out, 1); out << "const char* name;\n";
    Indent(out, 1); out << "TensorRole role;\n";
    Indent(out, 1); out << "int32_t blockIndex;\n";
    Indent(out, 1); out << "GGMLType type;\n";
    Indent(out, 1); out << "std::array<uint32_t, 4> dims;\n";
    Indent(out, 1); out << "uint32_t rank;\n";
    Indent(out, 1); out << "uint64_t encodedBytes;\n";
    Indent(out, 1); out << "uint64_t dataOffset;\n";
    Indent(out, 1); out << "uint64_t elementCount;\n";
    out << "};\n\n";
    
    out << "inline constexpr uint64_t kModelDataStart = " << genome.dataStart << "ULL;\n\n";
    
    // TensorId enum
    out << "enum class TensorId : uint32_t {\n";
    for (const auto& t : genome.tensors) {
        // Sanitize name for C++ enum
        std::string enumName = t.name;
        std::replace(enumName.begin(), enumName.end(), '.', '_');
        std::replace(enumName.begin(), enumName.end(), '-', '_');
        Indent(out, 1); out << enumName << " = " << t.tensorId << ",\n";
    }
    Indent(out, 1); out << "Count = " << genome.tensors.size() << "\n";
    out << "};\n\n";
    
    // ROM table
    out << "inline constexpr TensorROM kTensorROMTable[" << genome.tensors.size() << "] = {\n";
    for (const auto& t : genome.tensors) {
        Indent(out, 1); out << "{\n";
        Indent(out, 2); out << ".tensorId = " << t.tensorId << ",\n";
        Indent(out, 2); out << ".name = \"" << t.name << "\",\n";
        Indent(out, 2); out << ".role = " << FormatTensorRole(t.role) << ",\n";
        Indent(out, 2); out << ".blockIndex = " << t.blockIndex << ",\n";
        Indent(out, 2); out << ".type = GGMLType::" << (t.type == GGMLType::F32 ? "F32" : 
                            t.type == GGMLType::Q4_K ? "Q4_K" :
                            t.type == GGMLType::Q5_0 ? "Q5_0" :
                            t.type == GGMLType::Q6_K ? "Q6_K" : "Q8_0") << ",\n";
        Indent(out, 2); out << ".dims = " << FormatDims(t.dims) << ",\n";
        Indent(out, 2); out << ".rank = " << t.rank << ",\n";
        Indent(out, 2); out << ".encodedBytes = " << t.encodedBytes << "ULL,\n";
        Indent(out, 2); out << ".dataOffset = " << t.fileOffset << "ULL,\n";
        Indent(out, 2); out << ".elementCount = " << t.elementCount << "ULL\n";
        Indent(out, 1); out << "},\n";
    }
    out << "};\n\n";
    
    out << "inline constexpr uint32_t kTensorCount = " << genome.tensors.size() << ";\n\n";
    
    out << "} // namespace Generated\n";
    out << "} // namespace Deep2\n";
    out << "} // namespace RawrXD\n\n";
    
    out << "#endif // TENSOR_ROM_GENERATED_HPP\n";
    return true;
}

