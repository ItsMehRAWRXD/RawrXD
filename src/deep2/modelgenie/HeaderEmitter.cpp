HeaderEmitter::HeaderEmitter(const std::string& outputDir) : outputDir_(outputDir) {
    std::filesystem::create_directories(outputDir_);
}

std::ofstream HeaderEmitter::OpenHeader(const std::string& filename, const std::string& guardName) {
    std::filesystem::path fullPath = std::filesystem::path(outputDir_) / filename;
    std::ofstream out(fullPath);
    
    if (!out.is_open()) {
        return out;
    }
    
    out << "#ifndef " << guardName << "\n";
    out << "#define " << guardName << "\n\n";
    out << "//=============================================================================\n";
    out << "// AUTO-GENERATED by RAWRXD_MODEL_GENIE_HEADER_EXPORT_001\n";
    out << "// DO NOT EDIT MANUALLY\n";
    out << "// Source: NUGVERSE_ESTIMATOR_001 (frozen)\n";
    out << "//=============================================================================\n\n";
    out << "#pragma once\n\n";
    out << "#include <cstdint>\n";
    out << "#include <array>\n";
    out << "#include <optional>\n";
    out << "#include \"ModelGenome.hpp\"\n\n";
    
    return out;
}

void HeaderEmitter::WritePreamble(std::ofstream& out, const std::string& guardName, const std::string& description) {
    out << "// " << description << "\n";
    out << "// Generated from ModelGenome: " << guardName << "\n\n";
}

void HeaderEmitter::Indent(std::ofstream& out, int level) {
    for (int i = 0; i < level; ++i) out << "    ";
}

std::string HeaderEmitter::FormatDims(const std::array<uint32_t, 4>& dims) {
    std::stringstream ss;
    ss << "{";
    bool first = true;
    for (uint32_t d : dims) {
        if (d > 0) {
            if (!first) ss << ", ";
            ss << d;
            first = false;
        }
    }
    ss << "}";
    return ss.str();
}

std::string HeaderEmitter::FormatTensorRole(TensorRole role) {
    switch (role) {
        case TensorRole::Embed: return "TensorRole::Embed";
        case TensorRole::Output: return "TensorRole::Output";
        case TensorRole::Norm: return "TensorRole::Norm";
        case TensorRole::Attn: return "TensorRole::Attn";
        case TensorRole::FFN: return "TensorRole::FFN";
        case TensorRole::Router: return "TensorRole::Router";
        case TensorRole::Expert: return "TensorRole::Expert";
        case TensorRole::KVLatent: return "TensorRole::KVLatent";
        default: return "TensorRole::Unknown";
    }
}

std::string HeaderEmitter::FormatOpCode(OpCode opcode) {
    return std::to_string(static_cast<uint32_t>(opcode));
}

std::string HeaderEmitter::FormatPrimitive(Primitive prim) {
    return std::to_string(static_cast<uint32_t>(prim));
}

std::string HeaderEmitter::FormatOperandDomain(OperandDomain domain) {
    return std::to_string(static_cast<uint32_t>(domain));
}

std::string HeaderEmitter::FormatOperandRef(const OperandRef& ref) {
    std::stringstream ss;
    ss << "{" << FormatOperandDomain(ref.domain) << ", " << ref.id << "}";
    return ss.str();
}

std::string HeaderEmitter::FormatArchitecture(Architecture arch) {
    switch (arch) {
        case Architecture::DeepSeek2: return "Architecture::DeepSeek2";
        case Architecture::Llama: return "Architecture::Llama";
        case Architecture::Mistral: return "Architecture::Mistral";
        case Architecture::Qwen: return "Architecture::Qwen";
        case Architecture::GptOss: return "Architecture::GptOss";
        default: return "Architecture::Unknown";
    }
}

std::string HeaderEmitter::FormatRopeScaling(RopeScalingType scaling) {
    switch (scaling) {
        case RopeScalingType::Yarn: return "RopeScalingType::Yarn";
        case RopeScalingType::Linear: return "RopeScalingType::Linear";
        default: return "RopeScalingType::None";
    }
}

std::string HeaderEmitter::FormatWeightTying(WeightTying tying) {
    return tying == WeightTying::Tied ? "WeightTying::Tied" : "WeightTying::Untied";
}

bool HeaderEmitter::EmitAll(const ModelGenome& genome) {
    bool ok = true;
    ok &= EmitModelIdentity(genome);
    ok &= EmitModelConfig(genome);
    ok &= EmitTensorROM(genome);
    ok &= EmitBlockGenome(genome);
    ok &= EmitExecutionIR(genome);
    ok &= EmitCapabilityManifest(genome);
    ok &= EmitResidencyPlan(genome);
    ok &= EmitModelExport(genome);
    return ok;
}

