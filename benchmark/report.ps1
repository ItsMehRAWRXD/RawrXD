#!/usr/bin/env pwsh
# RawrXD Report Generator
# Generates human-readable reports from validation and benchmark outputs

param(
    [string]$ReportDir = "benchmark\reports",
    [string]$OutputDir = "benchmark\results",
    [string]$Format = "markdown"  # markdown, html, json
)

$ErrorActionPreference = "Stop"

Write-Host "========================================" -ForegroundColor Cyan
Write-Host "RawrXD Report Generator" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan

New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null

# Load validation report
$validationReport = $null
$validationPath = "$ReportDir\validation_report.json"
if (Test-Path $validationPath) {
    $validationReport = Get-Content $validationPath | ConvertFrom-Json
}

# Load benchmark report
$benchmarkReport = $null
$benchmarkPath = "$ReportDir\benchmark_report.json"
if (Test-Path $benchmarkPath) {
    $benchmarkReport = Get-Content $benchmarkPath | ConvertFrom-Json
}

if (-not $validationReport -and -not $benchmarkReport) {
    Write-Host "ERROR: No reports found. Run validate.ps1 and benchmark.ps1 first." -ForegroundColor Red
    exit 1
}

# Generate Markdown report
$report = @"
# RawrXD Validation & Benchmark Report

**Generated:** $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")  
**Commit:** $($benchmarkReport?.commit ?? $validationReport?.commit ?? "unknown")

---

## Executive Summary

| Metric | Value | Status |
|--------|-------|--------|
| Build | $(if (Test-Path "build\RawrXD.exe") { "✅ Success" } else { "❌ Failed" }) | - |
| Validation | $($validationReport?.summary?.passed ?? 0)/$($validationReport?.summary?.total ?? 0) passed | $(if ($validationReport?.summary?.failed -gt 0) { "⚠️" } else { "✅" }) |
| Performance | $(if ($benchmarkReport?.results) { "$([math]::Round(($benchmarkReport.results | Measure-Object -Property Ratio -Average).Average * 100, 1))% of baseline" } else { "N/A" }) | $(if ($benchmarkReport?.results -and ($benchmarkReport.results | Measure-Object -Property Ratio -Average).Average -lt 0.7) { "⚠️" } else { "✅" }) |

---

## Validation Results

"@

if ($validationReport) {
    $report += "| Test | Reference | Tolerance | Status | Duration |`n"
    $report += "|------|-----------|-----------|--------|----------|`n"
    
    foreach ($result in $validationReport.results) {
        $statusEmoji = switch ($result.Status) {
            "PASS" { "✅" }
            "FAIL" { "❌" }
            default { "⏳" }
        }
        $report += "| $($result.Name) | $($result.Reference) | $($result.Tolerance) | $statusEmoji $($result.Status) | $([math]::Round($result.Duration, 1))s |`n"
    }
    
    $report += "`n**Total Duration:** $([math]::Round($validationReport.duration_seconds / 60, 1)) minutes`n"
} else {
    $report += "_No validation report found. Run `.\benchmark\validate.ps1` first._`n"
}

$report += @"

---

## Performance Benchmarks

"@

if ($benchmarkReport -and $benchmarkReport.results) {
    $report += "| Model | Benchmark | RawrXD (tok/s) | llama.cpp (tok/s) | Ratio |`n"
    $report += "|-------|-----------|----------------|-------------------|-------|`n"
    
    foreach ($result in $benchmarkReport.results) {
        $ratioEmoji = if ($result.Ratio -ge 0.9) { "✅" } elseif ($result.Ratio -ge 0.7) { "⚠️" } else { "❌" }
        $report += "| $($result.Model) | $($result.Benchmark) | $($result.RawrXD_TPS) | $($result.LlamaCpp_TPS) | $ratioEmoji $([math]::Round($result.Ratio * 100, 1))% |`n"
    }
    
    $report += "`n**System:** $($benchmarkReport.system.cpu) | $($benchmarkReport.system.memory_gb) GB RAM`n"
    if ($benchmarkReport.system.gpu -ne "N/A") {
        $report += "**GPU:** $($benchmarkReport.system.gpu)`n"
    }
    $report += "**Total Duration:** $([math]::Round($benchmarkReport.duration_seconds / 60, 1)) minutes`n"
} else {
    $report += "_No benchmark report found. Run `.\benchmark\benchmark.ps1` first._`n"
}

$report += @"

---

## Reproduction Instructions

### Prerequisites
- Windows 10/11 or Linux
- CMake 3.20+
- Ninja 1.10+
- Python 3.9+
- (Optional) CUDA Toolkit 12.x for GPU support

### Quick Start
```powershell
# 1. Clone repository
git clone https://github.com/ItsMehRAWRXD/RawrXD.git
cd RawrXD

# 2. Checkout verified commit
git checkout $(if (Test-Path "benchmark\COMMIT_SHA") { Get-Content "benchmark\COMMIT_SHA" } else { "main" })

# 3. Build
.\benchmark\build.ps1

# 4. Validate
.\benchmark\validate.ps1

# 5. Benchmark
.\benchmark\benchmark.ps1

# 6. Generate report
.\benchmark\report.ps1
```

---

## Artifacts

- Build Manifest: `build\build_manifest.json`
- Validation Report: `benchmark\reports\validation_report.json`
- Benchmark Report: `benchmark\reports\benchmark_report.json`
- This Report: `benchmark\results\report.md`

---

*Generated by RawrXD Benchmark Package v1.0*
"@

# Write report
$reportPath = "$OutputDir\report.md"
$report | Set-Content $reportPath

Write-Host ""
Write-Host "Report generated: $reportPath" -ForegroundColor Green
Write-Host ""

# Print summary
if ($validationReport) {
    Write-Host "Validation: $($validationReport.summary.passed)/$($validationReport.summary.total) passed" -ForegroundColor $(if ($validationReport.summary.failed -eq 0) { "Green" } else { "Yellow" })
}
if ($benchmarkReport -and $benchmarkReport.results) {
    $avgRatio = ($benchmarkReport.results | Measure-Object -Property Ratio -Average).Average
    Write-Host "Performance: $([math]::Round($avgRatio * 100, 1))% of llama.cpp baseline" -ForegroundColor $(if ($avgRatio -ge 0.9) { "Green" } elseif ($avgRatio -ge 0.7) { "Yellow" } else { "Red" })
}

exit 0
