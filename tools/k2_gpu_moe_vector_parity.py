#!/usr/bin/env python3
"""Fail-closed full-vector comparison for Deep2 Kimi GPU0 parity receipts.

Input: three UTF-8 text files, one floating-point value per line (comments
starting with # and blank lines are ignored). Oracle must be generated by an
independent implementation, not the same optimized GEMV dispatch.
No numerical tolerance is assumed: thresholds must be supplied explicitly.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path


def load(path):
    raw = Path(path).read_bytes()
    values = []
    for line_no, line in enumerate(raw.decode("utf-8").splitlines(), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        try:
            value = float(line)
        except ValueError as exc:
            raise ValueError(f"{path}:{line_no}: invalid float") from exc
        if not math.isfinite(value):
            raise ValueError(f"{path}:{line_no}: nonfinite input")
        values.append(value)
    if not values:
        raise ValueError(f"{path}: empty vector")
    return values, hashlib.sha256(raw).hexdigest()


def compare(candidate, reference, epsilon):
    if len(candidate) != len(reference):
        raise ValueError(f"dimension mismatch: {len(candidate)} vs {len(reference)}")
    n = len(candidate)
    differences = [a - b for a, b in zip(candidate, reference)]
    abs_diff = [abs(v) for v in differences]
    max_index = max(range(n), key=lambda i: abs_diff[i])
    dot = math.fsum(a * b for a, b in zip(candidate, reference))
    a_norm = math.sqrt(math.fsum(a * a for a in candidate))
    b_norm = math.sqrt(math.fsum(b * b for b in reference))
    cosine = dot / (a_norm * b_norm) if a_norm and b_norm else (
        1.0 if a_norm == b_norm == 0 else 0.0
    )
    if not math.isfinite(cosine):
        raise ValueError("nonfinite cosine")
    relative = [d / max(abs(b), epsilon) for d, b in zip(abs_diff, reference)]
    rms = math.sqrt(math.fsum(d * d for d in differences) / n)
    ref_rms = math.sqrt(math.fsum(b * b for b in reference) / n)
    return {
        "elements": n,
        "max_abs": max(abs_diff),
        "mean_abs": math.fsum(abs_diff) / n,
        "rms_abs": rms,
        "rms_relative_to_reference": rms / max(ref_rms, epsilon),
        "max_relative": max(relative),
        "cosine_similarity": max(-1.0, min(1.0, cosine)),
        "worst_index": max_index,
        "worst_candidate": candidate[max_index],
        "worst_reference": reference[max_index],
        "nonfinite": 0,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cpu", required=True)
    parser.add_argument("--gpu", required=True)
    parser.add_argument("--oracle", required=True)
    parser.add_argument("--max-abs", required=True, type=float)
    parser.add_argument("--max-rms", required=True, type=float)
    parser.add_argument("--min-cosine", required=True, type=float)
    parser.add_argument("--epsilon", type=float, default=1e-8)
    parser.add_argument("--output", required=True)
    parser.add_argument("--oracle-provenance", required=True,
                        help="description or path identifying independent reference")
    args = parser.parse_args(argv)
    try:
        if (not all(math.isfinite(x) for x in
                    (args.max_abs, args.max_rms, args.min_cosine, args.epsilon))
                or args.max_abs < 0 or args.max_rms < 0
                or not -1 <= args.min_cosine <= 1 or args.epsilon <= 0):
            raise ValueError("invalid thresholds")
        vectors = {}
        hashes = {}
        for name in ("cpu", "gpu", "oracle"):
            vectors[name], hashes[name] = load(getattr(args, name))
        if len({len(v) for v in vectors.values()}) != 1:
            raise ValueError("input dimensions differ")
        comparisons = {
            "cpu_vs_oracle": compare(vectors["cpu"], vectors["oracle"], args.epsilon),
            "gpu_vs_oracle": compare(vectors["gpu"], vectors["oracle"], args.epsilon),
            "gpu_vs_cpu": compare(vectors["gpu"], vectors["cpu"], args.epsilon),
        }
        thresholds = {"max_abs": args.max_abs, "max_rms": args.max_rms,
                      "min_cosine": args.min_cosine}
        checks = {
            name: m["max_abs"] <= args.max_abs
            and m["rms_abs"] <= args.max_rms
            and m["cosine_similarity"] >= args.min_cosine
            for name, m in comparisons.items()
        }
        passed = all(checks.values())
        receipt = {
            "schema": "DEEP2_KIMI_GPU_MOE_NUMERICAL_PARITY_002/v1",
            "status": "PASS_DIAGNOSTIC" if passed else "FAIL",
            "certified": False,
            "oracle_provenance": args.oracle_provenance,
            "input_sha256": hashes,
            "thresholds": thresholds,
            "checks": checks,
            "comparisons": comparisons,
            "note": "Independent-oracle provenance and production tensor capture must be audited separately.",
        }
        Path(args.output).write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n",
                                     encoding="utf-8")
        print(receipt["status"])
        return 0 if passed else 2
    except (OSError, UnicodeError, ValueError, OverflowError) as exc:
        receipt = {"schema": "DEEP2_KIMI_GPU_MOE_NUMERICAL_PARITY_002/v1",
                   "status": "ERROR", "certified": False, "error": str(exc)}
        Path(args.output).write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
        print(f"ERROR: {exc}")
        return 3


if __name__ == "__main__":
    raise SystemExit(main())
