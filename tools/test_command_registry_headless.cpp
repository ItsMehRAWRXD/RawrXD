// Compiles and executes the actual production CommandRegistry implementation.
// No dummy registry and no model inference. Only Win32 built-in UI handlers are excluded.
#define RAWRXD_COMMAND_REGISTRY_HEADLESS
#include "../~dev/rawrxd/src/core/command_registry.cpp"
#include <atomic>
#include <iostream>
#include <stdexcept>
#include <thread>
int main() {
    auto& r = RawrXD::CommandRegistry::Instance();
    using RawrXD::Command;
    using RawrXD::CommandContext;
    int pass=0;
    auto test=[&](const char* name,bool ok){std::cout<<name<<"="<<(ok?"PASS":"FAIL")<<"\n";pass+=ok;};
    auto cmd=[](std::string id, RawrXD::CommandHandler handler) {
        Command c; c.id=std::move(id);c.title=c.id;c.handler=std::move(handler);return c;
    };
    test("01_missing_command",!r.ExecuteCommand("fixture.missing"));
    test("02_reject_empty_id",!r.RegisterCommand(cmd("",[](CommandContext&){})));
    test("03_reject_missing_handler",!r.RegisterCommand(cmd("fixture.nohandler",{})));
    int called=0;
    test("04_register",r.RegisterCommand(cmd("fixture.one",[&](CommandContext&){++called;})));
    test("05_duplicate_rejected",!r.RegisterCommand(cmd("fixture.one",[](CommandContext&){})));
    test("06_execute",r.ExecuteCommand("fixture.one")&&called==1);
    test("07_has_command",r.HasCommand("fixture.one"));
    test("08_nested_dispatch",r.RegisterCommand(cmd("fixture.nested",[&](CommandContext& c){if(!r.ExecuteCommand("fixture.one"))c.errorMessage="nested failed";}))&&r.ExecuteCommand("fixture.nested")&&called==2);
    test("09_context_mutation",r.RegisterCommand(cmd("fixture.context",[&](CommandContext&){r.SetContext("fixture.ready",true);}))&&r.ExecuteCommand("fixture.context")&&r.GetContext("fixture.ready"));
    auto conditioned=cmd("fixture.conditioned",[](CommandContext&){});conditioned.when={"fixture.enabled"};
    test("10_register_condition",r.RegisterCommand(conditioned));
    test("11_condition_denied",!r.ExecuteCommand("fixture.conditioned"));
    r.SetContext("fixture.enabled",true);
    test("12_condition_allowed",r.ExecuteCommand("fixture.conditioned"));
    test("13_exception_denied",r.RegisterCommand(cmd("fixture.throw",[](CommandContext&){throw std::runtime_error("fixture");}))&&!r.ExecuteCommand("fixture.throw"));
    test("14_error_denied",r.RegisterCommand(cmd("fixture.error",[](CommandContext& c){c.errorMessage="failure";}))&&!r.ExecuteCommand("fixture.error"));
    Command ext=cmd("fixture.ext",[&](CommandContext&){++called;});ext.keybinding="Ctrl+Alt+E";
    test("15_extension_register",r.RegisterExtensionCommand("fixture.publisher",ext));
    test("16_extension_duplicate",!r.RegisterExtensionCommand("fixture.other",ext));
    test("17_extension_keybinding",r.GetCommandForKeybinding("Ctrl+Alt+E")=="fixture.ext");
    test("18_extension_execute",r.ExecuteCommand("fixture.ext")&&called==3);
    r.UnregisterExtensionCommands("fixture.publisher");
    test("19_extension_unload",!r.HasCommand("fixture.ext"));
    test("20_extension_keybinding_cleanup",r.GetCommandForKeybinding("Ctrl+Alt+E").empty());
    test("21_extension_reinstall",r.RegisterExtensionCommand("fixture.publisher",ext));
    test("22_unregister",r.UnregisterCommand("fixture.one"));
    test("23_unregistered_denied",!r.ExecuteCommand("fixture.one"));
    std::atomic<int> concurrent{0};
    test("24_parallel_register",r.RegisterCommand(cmd("fixture.parallel",[&](CommandContext&){++concurrent;})));
    std::thread a([&]{for(int i=0;i<100;++i)r.ExecuteCommand("fixture.parallel");});
    std::thread b([&]{for(int i=0;i<100;++i)r.ExecuteCommand("fixture.parallel");});
    a.join();b.join();
    test("25_parallel_execution",concurrent==200);
    test("26_direct_unregister_extension",r.UnregisterCommand("fixture.ext"));
    test("27_reuse_id_by_new_owner",r.RegisterExtensionCommand("fixture.other",ext));
    r.UnregisterExtensionCommands("fixture.publisher");
    test("28_old_owner_does_not_delete_new_owner",r.HasCommand("fixture.ext"));
    r.UnregisterExtensionCommands("fixture.other");
    test("29_new_owner_unloads",!r.HasCommand("fixture.ext"));
    Command bindingOwner=cmd("fixture.binding.owner",[](CommandContext&){});
    bindingOwner.keybinding="Ctrl+Alt+Collision";
    test("30_register_binding_owner",r.RegisterCommand(bindingOwner));
    Command conflict=cmd("fixture.binding.conflict",[](CommandContext&){});
    conflict.keybinding="Ctrl+Alt+Collision";
    test("31_builtin_collision_denied",!r.RegisterCommand(conflict));
    test("32_original_binding_intact",r.GetCommandForKeybinding("Ctrl+Alt+Collision")=="fixture.binding.owner");
    Command extensionConflict=cmd("fixture.binding.extension",[](CommandContext&){});
    extensionConflict.keybinding="Ctrl+Alt+Collision";
    test("33_extension_collision_denied",!r.RegisterExtensionCommand("fixture.attacker",extensionConflict));
    test("34_no_partial_extension_register",!r.HasCommand("fixture.binding.extension"));
    test("35_original_command_survives",r.ExecuteCommand("fixture.binding.owner"));
    r.RegisterKeybinding("Ctrl+Alt+Collision", "fixture.binding.conflict");
    test("36_manual_hijack_denied",r.GetCommandForKeybinding("Ctrl+Alt+Collision")=="fixture.binding.owner");
    r.RegisterKeybinding("Ctrl+Alt+Missing", "fixture.unknown");
    test("37_unknown_target_denied",r.GetCommandForKeybinding("Ctrl+Alt+Missing").empty());
    r.RegisterKeybinding("", "fixture.binding.owner");
    test("38_empty_shortcut_denied",r.GetCommandForKeybinding("").empty());
    auto paletteCmd=cmd("Fixture.MixedCASE",[](CommandContext&){});
    paletteCmd.title="MixedCASE Palette";
    test("39_palette_register",r.RegisterCommand(paletteCmd));
    auto found=r.SearchCommands("mixedcase");
    bool present=false;for(const auto& item:found)if(item.id=="Fixture.MixedCASE")present=true;
    test("40_palette_case_insensitive",present);
    auto blocked=cmd("fixture.hidden.when",[](CommandContext&){});
    blocked.title="ContextHiddenTest";
    blocked.when={"fixture.never.enabled"};
    test("41_palette_condition_register",r.RegisterCommand(blocked));
    bool hidden=true;for(const auto& item:r.SearchCommands("ContextHiddenTest"))if(item.id=="fixture.hidden.when")hidden=false;
    test("42_palette_condition_hidden",hidden);
    r.SetContext("fixture.never.enabled",true);
    bool visible=false;for(const auto& item:r.SearchCommands("ContextHiddenTest"))if(item.id=="fixture.hidden.when")visible=true;
    test("43_palette_condition_visible",visible);
    Command snapshot;
    test("44_snapshot_found",r.TryGetCommand("fixture.binding.owner",snapshot));
    test("45_snapshot_id",snapshot.id=="fixture.binding.owner");
    test("46_snapshot_missing",!r.TryGetCommand("fixture.not.registered",snapshot));
    test("47_snapshot_survives_unload",r.UnregisterCommand("fixture.binding.owner") && snapshot.id=="fixture.binding.owner");
    test("48_snapshot_copy_handler",static_cast<bool>(snapshot.handler));
    auto legacy=cmd("fixture.legacy.snapshot",[](CommandContext&){});
    test("49_legacy_register",r.RegisterCommand(legacy));
    const Command* retained=r.GetCommand("fixture.legacy.snapshot");
    test("50_legacy_pointer_nonnull",retained!=nullptr);
    test("51_legacy_id_matches",retained && retained->id=="fixture.legacy.snapshot");
    test("52_legacy_unload",r.UnregisterCommand("fixture.legacy.snapshot"));
    test("53_legacy_pointer_survives_unload",retained && retained->id=="fixture.legacy.snapshot");
    test("54_legacy_missing",r.GetCommand("fixture.legacy.snapshot")==nullptr);
    test("55_legacy_missing_does_not_invalidate",retained && retained->id=="fixture.legacy.snapshot");
    auto alias=cmd("fixture.alias",[](CommandContext&){});
    test("56_alias_register",r.RegisterCommand(alias));
    r.RegisterKeybinding("Ctrl+Alt+Alias","fixture.alias");
    test("57_alias_resolves",r.GetCommandForKeybinding("Ctrl+Alt+Alias")=="fixture.alias");
    test("58_alias_unregister",r.UnregisterCommand("fixture.alias"));
    test("59_alias_removed",r.GetCommandForKeybinding("Ctrl+Alt+Alias").empty());
    auto extAlias=cmd("fixture.ext.alias",[](CommandContext&){});
    test("60_extension_alias_register",r.RegisterExtensionCommand("fixture.alias.owner",extAlias));
    r.RegisterKeybinding("Ctrl+Alt+ExtensionAlias","fixture.ext.alias");
    test("61_extension_alias_resolves",r.GetCommandForKeybinding("Ctrl+Alt+ExtensionAlias")=="fixture.ext.alias");
    r.UnregisterExtensionCommands("fixture.alias.owner");
    test("62_extension_alias_removed",r.GetCommandForKeybinding("Ctrl+Alt+ExtensionAlias").empty());
    CommandContext reuse;
    reuse.errorMessage="stale error";
    reuse.handled=true;
    test("63_context_reuse_success",r.ExecuteCommand("fixture.one",reuse));
    test("64_context_reuse_clears_error",reuse.errorMessage.empty());
    test("65_context_reuse_sets_id",reuse.commandId=="fixture.one");
    test("66_context_reuse_handled",reuse.handled);
    test("67_context_failure_sets_error",!r.ExecuteCommand("fixture.not.registered",reuse)&&!reuse.errorMessage.empty());
    test("68_context_failure_clears_handled",!reuse.handled);
    test("69_context_recover_after_failure",r.ExecuteCommand("fixture.one",reuse)&&reuse.errorMessage.empty()&&reuse.handled);
    std::cout<<"CENTRAL_REGISTRY="<<pass<<"/69\n";
    return pass==69?0:1;
}
