Write-Host "  model   : $Model"
Write-Host "  rawr    : $Rawr"
Write-Host "  repo    : $RepoRoot"
Write-Host "  usage   : Invoke-RawrResponse 'your request here'"
Write-Host "  same KV : NO (one-shot rawr run; logical context only)"
