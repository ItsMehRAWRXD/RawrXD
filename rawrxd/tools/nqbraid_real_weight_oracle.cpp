int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr,
            "Usage: %s <model.gguf> <model.q0.nqb> [prompt]\n"
            "  prompt defaults to \"The capital of France is\"\n",
            argv[0]);
        return 64;
    }
    const char* ggufPath = argv[1];
    const char* nqbPath  = argv[2];
    const char* prompt   = (argc > 3) ? argv[3] : "The capital of France is";

    Receipt r{};
    r.modelPath = ggufPath;
    r.nqbPath   = nqbPath;
    // RAWRXD_NQB_PROVENANCE_001 -- measure the inputs rather than naming them.
    // A path identifies a location, not an artefact: the .nqb in this tree was
    // deleted and regenerated during the run that produced the first receipt,
    // so the same path held different bytes minutes apart. The size is what
    // distinguishes them, and a size of 0 means the file was not there.
    r.modelBytes = fileSizeOf(ggufPath);
    r.nqbBytes   = fileSizeOf(nqbPath);
    std::fprintf(stderr, "MODEL_SIZE_BYTES=%llu NQB_SIZE_BYTES=%llu\n",
                 (unsigned long long)r.modelBytes,
                 (unsigned long long)r.nqbBytes);

    std::fprintf(stderr, "GATE=NQBRAID_REAL_WEIGHT_ORACLE\n");
    RAWRXD_PRINT_BUILD_IDENTITY();
    std::fprintf(stderr, "MODEL_GGUF=%s\n", ggufPath);
    std::fprintf(stderr, "MODEL_NQB=%s\n", nqbPath);
    std::fprintf(stderr, "PROMPT=%s\n", prompt);

    // ----------------------------------------------------------------
    // 1. Initialise registry (required before any quant operation)
    // ----------------------------------------------------------------
    Deep2::QuantKernelRegistry::Instance().Initialize();

    // ----------------------------------------------------------------
    // 2. Load GGUF path
    // ----------------------------------------------------------------
    _putenv_s("DEEP2_DEBUG_EXPOSE_LOGITS", "1");
    Deep2Engine refEngine;
    Deep2::ModelLoadDiag refDiag;

    if (!refEngine.loadModel(ggufPath, &refDiag)) {
        std::snprintf(r.detail, sizeof r.detail, "GGUF load failed: stage=%d name='%s' msg='%s'",
                      refDiag.stageCode, refDiag.stageName.c_str(), refDiag.message.c_str());
        r.verdict = "FAIL_GGUF_LOAD";
        printReceipt(r);
        return 1;
    }
    std::fprintf(stderr, "GGUF_LOAD=PASS\n");

    // ----------------------------------------------------------------
    // 3. Load NQB path
    // ----------------------------------------------------------------
    _putenv_s("DEEP2_DEBUG_EXPOSE_LOGITS", "1");
    Deep2Engine nqbEngine;
    if (!nqbEngine.loadModelFromNanof32Braid(nqbPath)) {
        std::snprintf(r.detail, sizeof r.detail, "NQB load failed");
        r.verdict = "FAIL_NQB_LOAD";
        printReceipt(r);
        return 1;
    }
    std::fprintf(stderr, "NQB_LOAD=PASS\n");

    // ----------------------------------------------------------------
    // 4. Verify vocabulary identity (token IDs must match)
    // ----------------------------------------------------------------
    std::vector<int> refIds = refEngine.tokenize(prompt);
    std::vector<int> nqbIds = nqbEngine.tokenize(prompt);
    r.tokenIdsIdentical = (refIds.size() == nqbIds.size()) &&
                          std::equal(refIds.begin(), refIds.end(), nqbIds.begin());
    if (!r.tokenIdsIdentical) {
        std::snprintf(r.detail, sizeof r.detail,
                      "Token IDs differ: ref=%zu nqb=%zu",
                      refIds.size(), nqbIds.size());
        r.verdict = "FAIL_TOKEN_IDS_DIFFER";
        printReceipt(r);
        return 1;
    }
    std::fprintf(stderr, "TOKEN_IDS_IDENTICAL=1 count=%zu\n", refIds.size());

    // ----------------------------------------------------------------
    // 5. Verify all dequantised weights are finite
    // ----------------------------------------------------------------
    // The converter already dequantised every tensor; we verify by loading
    // one representative block and checking finiteness.  A full tensor scan
    // would be quadratic; this is a spot check on the first block of the first
    // Q2_K tensor.
    {
        Deep2::GGUFLoader loader;
        if (loader.load(ggufPath)) {
            auto* t = loader.getTensor("blk.0.attn_q.weight");
            if (t && t->type == Deep2::GGMLType::GGML_TYPE_Q2_K) {
                std::vector<float> buf(t->numElements());
                auto fn = Deep2::QuantKernelRegistry::Instance().GetDequant(10);
                if (fn) {
                    fn(t->data, buf.data(), buf.size());
                    r.weightDecodeFinite = allFinite(buf.data(), buf.size());
                }
            }
        }
    }
    std::fprintf(stderr, "WEIGHT_DECODE_FINITE=%d\n", r.weightDecodeFinite);

    // ----------------------------------------------------------------
    // 6. Run one generation step on both paths, capture logits
    // ----------------------------------------------------------------
    std::vector<float> refLogits, nqbLogits;
    if (!runOneToken(refEngine, refLogits, r)) {
        r.verdict = "FAIL_REF_GENERATE";
        printReceipt(r);
        return 1;
    }
    if (!runOneToken(nqbEngine, nqbLogits, r)) {
        r.verdict = "FAIL_NQB_GENERATE";
        printReceipt(r);
        return 1;
    }
    if (refLogits.size() != nqbLogits.size()) {
        std::snprintf(r.detail, sizeof r.detail,
                      "Logit size mismatch: ref=%zu nqb=%zu",
                      refLogits.size(), nqbLogits.size());
        r.verdict = "FAIL_LOGIT_SIZE_MISMATCH";
        printReceipt(r);
        return 1;
    }
    std::fprintf(stderr, "LOGIT_CAPTURE=PASS size=%zu\n", refLogits.size());

    // ----------------------------------------------------------------
    // 7. Compare logits
    // ----------------------------------------------------------------
    r.metrics = compareLogits(refLogits.data(), nqbLogits.data(), refLogits.size());

    // ----------------------------------------------------------------
    // 8. First divergence stage
    // ----------------------------------------------------------------
    // RAWRXD_NQBRAID_HONEST_STAGE_001 -- this used to read:
    //     r.firstDivergenceStage = "LOGITS";   // hardcoded
    // while the file header asserted
    //     FIRST_DIVERGENCE_STAGE named from parity checkpoints, not guessed.
    // No parity probe is ever enabled by this tool, so there were no
    // checkpoints to read and the stage name was a constant wearing the
    // costume of a measurement. A field that always says LOGITS tells a reader
    // "the logits were the first thing to differ" when the truth is "no earlier
    // stage was ever examined". Those are different claims and only one of them
    // is actionable, because the actionable one names where to look next.
    //
    // Reported honestly until a probe actually runs:
    //   NOT_MEASURED_NO_PARITY_PROBE  no earlier stage was examined
    //   LOGITS                        an earlier stage was compared and agreed
    // The distinction matters: the current FAIL_LOGIT_DIVERGENCE says nothing
    // about whether layer 0 already diverges.
    const bool parityProbeRan = false;   // no probe is enabled by this tool
    r.firstDivergenceStage = parityProbeRan ? "LOGITS"
                                            : "NOT_MEASURED_NO_PARITY_PROBE";
    std::fprintf(stderr,
        "FIRST_DIVERGENCE_STAGE=%s (earlier stages compared: %s)\n",
        r.firstDivergenceStage, parityProbeRan ? "yes" : "no");

    // ----------------------------------------------------------------
    // 9. Writer/reader parity -- MEASURED, not asserted
    // ----------------------------------------------------------------
    // RAWRXD_NQBRAID_MEASURED_WRITER_READER_001 -- this used to read:
    //     r.nqbWriterReaderParity = true;   // converter verified by its own round-trip
    // A literal `true` in a receipt is the exact shape of the retracted
    // false-PASS receipts in this repository's ledger: a field that reads like
    // an observation and can never report the alternative. The comment was also
    // false -- the converter performs no round-trip; it only writes. The
    // separate nqb_reopen_parity_probe does measure it, but that is a different
    // executable and its result is not visible from inside this receipt.
    //
    // So it is measured here: the NQB reader's own copy of one real tensor is
    // compared against the values the GGUF dequantizer produces for the same
    // tensor, after the same BF16 narrowing the reader performs. Agreement to
    // BF16 rounding proves the container carried the weights intact.
    r.nqbWriterReaderParity = measureWriterReaderParity(nqbPath, ggufPath);
    std::fprintf(stderr, "NQB_WRITER_READER_PARITY_MEASURED=%d\n",
                 r.nqbWriterReaderParity ? 1 : 0);

    // ----------------------------------------------------------------
    // 10. Verdict
    // ----------------------------------------------------------------
    r.modelReferenceParity = (r.metrics.argmaxMatch && r.metrics.top5Overlap == 5);

    if (r.metrics.argmaxMatch && r.metrics.maxAbsDiff < 1e-3) {
        r.verdict = "PASS";
    } else if (r.metrics.argmaxMatch) {
        r.verdict = "PASS_WITH_TOLERANCE";
    } else {
        r.verdict = "FAIL_LOGIT_DIVERGENCE";
    }

    std::fprintf(stderr, "\n=== RAWRXD_NQBRAID_REAL_WEIGHT_ORACLE_001 RECEIPT ===\n");
    printReceipt(r);
    return (std::strcmp(r.verdict, "PASS") == 0) ? 0 : 1;
}
