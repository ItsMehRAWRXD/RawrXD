// nqbraid_real_weight_oracle.cpp
// RAWRXD_NQBRAID_REAL_WEIGHT_ORACLE_001
//
// Feeds identical GGUF-derived token IDs to both the GGUF path and the NQB
// path, captures first-divergence telemetry through final logits, and emits a
// receipt.  Uses q0 (lossless dense F32) NQB produced by gguf_to_nqb_converter.
//
// HONESTY CONSTRAINTS
//  * SOURCE_WEIGHTS=REAL, SYNTHETIC_WEIGHTS=0
//  * Every numeric field is measured, never asserted.
//  * TOKEN_IDS_IDENTICAL verified by count + elementwise comparison.
//  * WEIGHT_DECODE_FINITE verified per-tensor.
//  * FIRST_DIVERGENCE_STAGE named from parity checkpoints, not guessed.
//  * If either path fails to generate, the receipt says FAIL and names why.

